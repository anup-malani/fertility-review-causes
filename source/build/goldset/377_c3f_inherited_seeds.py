#!/usr/bin/env python3
"""
377 — C.3.f (TICK-086) stage-3 input: harvest the records D.1.b routed OUT to this chapter.

Why this exists. TICK-063 (D.1.b, cultural westernization) screened a 4,701-record citation pool
under six boundary walls, and Wall 1 is C.3.f: "a study measuring transfers, their direction, or
their magnitude routes to OFF_WEALTH_FLOWS_C3f even when it cites Caldwell's cultural argument in
its framing." That screen put 28 records in the C.3.f queue. They are hand-adjudicated seeds from a
sibling chapter's rubric and they cost nothing to collect, so they are collected BEFORE a frame is
built rather than rediscovered inside it (`snowball-pools-omit-their-own-seeds`).

What this script does and does not do. It copies the queue out of the 063 branch with the commit it
came from, and cross-tabs it on the two axes that decide whether a seed is usable at all. It does
NOT decide the routing: the reasons were written by a screen answering a different chapter's
question, and a keyword rule over another rubric's prose is exactly the automated hand-read that
`dont-automate-a-hand-read-seed-choice` warns against. Every record is printed for reading, and the
routing is recorded in the scope document by hand.

The two axes, and why they are the right ones:
  OUTCOME     D.1.b's Wall 1 fires on the EXPOSURE (a transfer) and says nothing about the outcome.
              A record about elder care with no fertility outcome satisfies Wall 1 and is still
              useless here. `venue-comparison-conditions-on-outcome` is the same shape.
  OWNER       Wall 1 routes anything upward-flowing to C.3.f, but the policy-identified corner of
              upward flows is C.3.c (old-age security), a CLOSED chapter. A pension-crowdout study
              is not C.3.f's to claim, and 376 already put the pension vocabulary at 162 records
              inside this frame.

Output literature/search-logs/c3f-inherited-seeds-<date>.{json,md}. No network access.
"""
import json, subprocess, datetime, pathlib, re, sys

SOURCE_BRANCH = "063-caldwell-wealth-flows-westernization"
SOURCE_PATH = "output/caldwell-wealth-flows-westernization-PARTIAL-routing-queues.json"
QUEUE_KEY = "C.3.f"


def git(*args):
    p = subprocess.run(["git", *args], capture_output=True, text=True)
    if p.returncode != 0:
        sys.exit(f"git {' '.join(args)} failed: {p.stderr.strip()[:300]}")
    return p.stdout


def main():
    date = datetime.date.today().isoformat()
    sha = git("rev-parse", SOURCE_BRANCH).strip()
    queue = json.loads(git("show", f"{SOURCE_BRANCH}:{SOURCE_PATH}"))[QUEUE_KEY]

    # Flags for READING, not for routing. Each is a question the reader must answer, and the flag
    # only says which records to look at first.
    fert = re.compile(r"fertility|birth|childbear|family size|number of children", re.I)
    pension = re.compile(r"pension|social security|old.age (security|insurance)|long.term care "
                         r"insurance", re.I)
    for r in queue:
        text = f"{r['title']} {r['reason']}"
        r["flag_outcome_named"] = bool(fert.search(text))
        r["flag_pension_vocabulary"] = bool(pension.search(text))

    n = len(queue)
    with_outcome = sum(r["flag_outcome_named"] for r in queue)
    with_pension = sum(r["flag_pension_vocabulary"] for r in queue)
    print(f"{n} records inherited from {SOURCE_BRANCH} @ {sha[:8]}")
    print(f"  a fertility outcome is named in title or reason: {with_outcome}")
    print(f"  pension / old-age-insurance vocabulary present:   {with_pension}")
    print(f"  neither:  {sum(1 for r in queue if not r['flag_outcome_named'] and not r['flag_pension_vocabulary'])}")
    print()
    for i, r in enumerate(sorted(queue, key=lambda r: -(r["year"] or 0)), 1):
        mark = ("F" if r["flag_outcome_named"] else "-") + ("P" if r["flag_pension_vocabulary"] else "-")
        print(f"{i:>3} [{mark}] {r['year']}  {r['title'][:96]}")
        print(f"         {r['doi'] or 'no doi'}  ({r['paperId']})")
        print(f"         {r['reason']}")

    logs = pathlib.Path("literature/search-logs")
    blob = {"date": date, "source_branch": SOURCE_BRANCH, "source_commit": sha,
            "source_path": SOURCE_PATH, "queue_key": QUEUE_KEY, "n": n,
            "flag_counts": {"fertility_outcome_named": with_outcome,
                            "pension_vocabulary": with_pension},
            "note": "Flags mark records to read first. Routing is decided by hand in the scope "
                    "document; these reasons were written by another chapter's rubric.",
            "records": queue}
    (logs / f"c3f-inherited-seeds-{date}.json").write_text(json.dumps(blob, indent=2) + "\n")

    md = [f"# C.3.f inherited seeds — {date}", "",
          f"The {n} records TICK-063 (D.1.b) routed to `OFF_WEALTH_FLOWS_C3f`, taken from",
          f"`{SOURCE_BRANCH}` at `{sha[:8]}`. Generated by",
          "`source/build/goldset/377_c3f_inherited_seeds.py`; do not edit by hand.", "",
          "D.1.b's Wall 1 fires on the **exposure** — anything measuring a transfer, its direction",
          "or its magnitude — and says nothing about the outcome or about which sibling owns it.",
          "So these are candidates to read, not a routed set to adopt. `F` = a fertility outcome is",
          "named in the title or the reason; `P` = pension or old-age-insurance vocabulary, which",
          "is C.3.c's corner and C.3.c is a closed chapter.", "",
          f"- a fertility outcome is named: **{with_outcome} of {n}**",
          f"- pension vocabulary present: **{with_pension} of {n}**", "",
          "| | year | title | DOI | D.1.b's reason |", "|---|---|---|---|---|"]
    for r in sorted(queue, key=lambda r: -(r["year"] or 0)):
        mark = ("F" if r["flag_outcome_named"] else "·") + ("P" if r["flag_pension_vocabulary"] else "·")
        t = r["title"].replace("|", "\\|")
        md.append(f"| `{mark}` | {r['year']} | {t} | `{r['doi'] or '—'}` | {r['reason']} |")
    md.append("")
    (logs / f"c3f-inherited-seeds-{date}.md").write_text("\n".join(md))
    print(f"\nwrote c3f-inherited-seeds-{date}.json and .md")


main()
