#!/usr/bin/env python3
"""
142_b6_library_wantlist.py — B.6, stage 5 handoff. The residual procurement list for a human.

Everything two automated passes could not reach, ordered so that a person with a Zotero connector and
the UChicago proxy works the highest-value records first and can stop at any point having done the
most valuable part. C.2.c is the precedent: TICK-056 recovered 15 of 15 core records and unblocked
extraction; B.1 is the counter-example, stalled at 20 of 95 since 2026-07-25.

Two distinctions the list preserves, because they need different actions:

  * ROUTE-BLOCKED (OpenAlex says open, the fetch was refused). A proxy is usually unnecessary — the
    paper is free and the publisher merely refuses scripts. Often one click in a browser. 73 records.
  * CLOSED (no open version exists). Needs the proxy or interlibrary loan. 47 records.

Ordering is by retrieval VALUE, not by tier or citation count:
  1. Job A primary-cell records, since they are the only ones that earn causal GRADE credit;
  2. within Job A, records the screen flagged IMPORTANT, then the PFAS half — because the realised
     retrieval is family-biased against PFAS (51% vs 59% after recovery, and 38% vs 59% before it),
     so working PFAS first shrinks the bias rather than entrenching it;
  3. Job A2 input cells, then Job B held records (each settles one routing question and is therefore
     cheap to resolve), then Job C parameters.

Records the screen identified as shadows or duplicates are EXCLUDED from the list and reported
separately, because asking a human to procure a peer-review artefact or a conference abstract of a
paper already held is a waste of the scarcest resource in this pipeline.

Output: literature/search-logs/{slug}-library-wantlist.md
        extraction/{slug}-library-dois.txt
"""
import csv, os, re

SLUG = "microplastics-pfas-reproductive"
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
LOGS = os.path.join(ROOT, "literature", "search-logs")
EXTRACT = os.path.join(ROOT, "extraction")
PDF_DIR = os.path.join(ROOT, "literature", "pdfs", SLUG)
LOG1 = os.path.join(EXTRACT, f"{SLUG}-pdf-retrieval-log.csv")
GATE = os.path.join(EXTRACT, f"{SLUG}-ra-gate.csv")
OUT_MD = os.path.join(LOGS, f"{SLUG}-library-wantlist.md")
OUT_DOI = os.path.join(EXTRACT, f"{SLUG}-library-dois.txt")

JOB_ORDER = {"A_primary": 0, "A2_input": 1, "B_held": 2, "C_parameter": 3}
JOB_LABEL = {"A_primary": "A — primary cell (causal GRADE credit)",
             "A2_input": "A2 — fertility-input cell (semen, ovarian)",
             "B_held": "B — held, settles one routing question",
             "C_parameter": "C — parameter, pharmacokinetic, measurement"}
# Screen notes that mark a record as not worth a human's time to procure.
SKIP_MARKERS = ("SHADOW RECORD", "DUPLICATE of", "duplicate index record",
                "Conference abstract of preliminary", "correspondence attached")


def slugify(t):
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", (t or "").lower()))[:60].strip("-")


def main():
    readable = {f.split("__")[0] for f in os.listdir(PDF_DIR)
                if f.endswith(".txt") and os.path.getsize(os.path.join(PDF_DIR, f)) > 500}
    rows = list(csv.DictReader(open(LOG1)))
    gate = {r["openalex_id"]: r for r in csv.DictReader(open(GATE))}

    residual = [r for r in rows if r["openalex_id"] not in readable]
    skipped, wanted = [], []
    for r in residual:
        note = (gate.get(r["openalex_id"], {}) or {}).get("screen_note", "")
        if any(m in note for m in SKIP_MARKERS):
            skipped.append((r, note))
        else:
            r["_note"] = note
            wanted.append(r)

    def sort_key(r):
        note = r.get("_note", "")
        return (JOB_ORDER.get(r["job"], 9),
                0 if "IMPORTANT" in note else 1,
                0 if r["chemical_family"] == "pfas" else 1,
                r["oa_status"] == "closed",          # route-blocked first: cheaper to get
                -(len(note)))
    wanted.sort(key=sort_key)

    open(OUT_DOI, "w").write("\n".join(dict.fromkeys(r["doi"] for r in wanted if r["doi"])) + "\n")

    n_blocked = sum(1 for r in wanted if r["oa_status"] not in ("closed", "UNCONFIRMED"))
    n_closed = sum(1 for r in wanted if r["oa_status"] == "closed")
    by_job = {}
    for r in wanted:
        by_job.setdefault(r["job"], []).append(r)

    L = [f"# Library procurement list — {SLUG} (B.6)", "",
         "Generated by `source/build/goldset/142_b6_library_wantlist.py` after two automated passes "
         "(`140` publisher and repository routes, `141` NCBI efetch for PMC author manuscripts).", "",
         f"**{len(readable)} of {len(rows)} records are already readable ({len(readable) / len(rows):.0%}).** "
         f"This list holds the **{len(wanted)}** that need a human, plus **{len(skipped)}** deliberately "
         "excluded as shadow or duplicate records (listed at the foot — do not procure them).", "",
         f"- **{n_blocked} are ROUTE-BLOCKED**: OpenAlex reports an open version and the publisher "
         "simply refuses a scripted download. A proxy is usually unnecessary; a browser and a click "
         "will often do it.",
         f"- **{n_closed} are CLOSED**: no open version exists. These need the UChicago proxy or ILL.", "",
         "## Work it in this order, and stop wherever you run out of time", "",
         "The ordering is by retrieval value, not by tier or citations. Job A first because those are "
         "the only records that earn causal GRADE credit. Within Job A, the records the screen flagged "
         "IMPORTANT, then **the PFAS half before the microplastics half** — the realised retrieval is "
         "biased against PFAS (51% vs 59% after recovery; 38% vs 59% before it), and since this "
         "chapter's design is a comparison between its two halves, working PFAS first shrinks that "
         "bias instead of entrenching it. Route-blocked before closed within each group, because "
         "route-blocked records are cheaper.", ""]

    for job in ("A_primary", "A2_input", "B_held", "C_parameter"):
        rs = by_job.get(job, [])
        if not rs:
            continue
        got = sum(1 for r in rows if r["job"] == job and r["openalex_id"] in readable)
        tot = sum(1 for r in rows if r["job"] == job)
        L += ["", f"## Job {JOB_LABEL[job]}", "",
              f"*{got}/{tot} already readable; {len(rs)} listed here.*", ""]
        for r in rs:
            st = r["oa_status"]
            mark = "**CLOSED — needs proxy/ILL**" if st == "closed" else f"route-blocked (OA: {st})"
            tgt = f"literature/pdfs/{SLUG}/{r['openalex_id']}__{slugify(r['title'])}.pdf"
            L.append(f"- **{r['title'][:92]}**  \n"
                     f"  `{r['doi'] or 'NO DOI'}` · {mark} · family `{r['chemical_family'] or '—'}`  \n"
                     f"  → save as `{tgt}`")
            if r.get("_note"):
                L.append(f"  *{r['_note'][:180]}*")

    if skipped:
        L += ["", "## Do NOT procure these", "",
              "The screen identified each of these as a shadow record (a peer-review artefact, an "
              "author response, a comment) or a duplicate of a record already held. They are in the "
              "frame because open-peer-review journals mint a DOI per referee report; they are not "
              "studies and procuring them wastes the scarcest resource in this pipeline.", ""]
        for r, note in skipped:
            L.append(f"- {r['title'][:88]} — *{note[:110]}*")

    L += ["", "## What this list cannot buy", "",
          "Full retrieval of every record here would not change the chapter's central findings, and "
          "the procurement effort should be spent knowing that. The screen established over 920 "
          "records that no study estimates either exposure against a population fertility quantity "
          "with an identifying design; that `PRIMARY_HIGH_EXPOSURE` is empty, so the contaminated-"
          "community cohorts carrying the only exogenous exposure variation have never been studied "
          "for a fertility outcome; and that whether an estimate handles the parity/excretion "
          "reverse-causation problem is a property of how each study was built. What this list buys "
          "is the ability to say precisely what each included study does and does not identify."]
    open(OUT_MD, "w").write("\n".join(L) + "\n")

    print(f"readable={len(readable)}/{len(rows)} wanted={len(wanted)} "
          f"(route-blocked {n_blocked}, closed {n_closed}) skipped_as_shadow={len(skipped)}")
    for job in ("A_primary", "A2_input", "B_held", "C_parameter"):
        if job in by_job:
            print(f"  {job:<12} {len(by_job[job])} to procure")
    print(f"-> {os.path.relpath(OUT_MD, ROOT)}")


if __name__ == "__main__":
    main()
