#!/usr/bin/env python3
"""314 — C.6.a retrieval handoff, split by what a human would actually have to do. TICK-078.

A.17 found that 67 of its 98 retrieval failures were OPEN urls killed by bot defence, not paywalls,
and that a single undifferentiated "missing PDFs" list sends a person to the wrong tool
(`blocked-route-is-not-a-paywall`). So the handoff is split:

  BROWSER JOB  the URL is open; a logged-in browser session gets it. `blocked` + `landing_only`.
  PROXY JOB    no open copy exists; needs the UChicago proxy or ILL. `paywalled`.

And it is ORDERED BY CELL, not by convenience. A retrieval rate hides which records are missing
(`retrieval-rate-hides-which-records`): 12% overall is bad, but 0 of 5 on `BENCHMARK_MEASURED` --
the cell scope §4 called the value-added cell -- is what actually decides whether this chapter has a
primary identification claim. The gate below is stated in those terms.

Usage: python3 source/build/goldset/314_c6a_retrieval_handoff.py
"""
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LOGS = ROOT / "literature" / "search-logs"
S = json.loads((LOGS / "easterlin-relative-income-retrieval-state.json").read_text())
OUT = LOGS / "easterlin-relative-income-retrieval-handoff.md"

# Priority order: the cell whose emptiness would cost the chapter the most, first.
CELL_ORDER = ["BENCHMARK_MEASURED", "RIVAL_TEST", "CYCLE_TEST", "COHORT_SIZE_FERTILITY",
              "RELATIVE_INCOME_FERTILITY", "MIXED_COHORT_MARRIAGE"]
BROWSER = {"blocked", "landing_only"}
PROXY = {"paywalled", "found_not_fetched"}

recs = S["records"]
by_cell = defaultdict(Counter)
for r in recs.values():
    by_cell[r["cell"]][r["status"]] += 1

L = ["# C.6.a full-text retrieval — handoff", "",
     "Generated by `source/build/goldset/314_c6a_retrieval_handoff.py`. Do not edit by hand.", "",
     f"Queue was **{S['n']}** records: every primary cell plus `MIXED_COHORT_MARRIAGE` (Wall 3). "
     f"`LINK1_LABOUR` and `THEORY` are context by scope §3 and were not retrieved.", "",
     "## What the automated pass reached, by cell", "",
     "| cell | have | browser job | proxy job | total |", "|---|---|---|---|---|"]
tot = Counter()
for cell in CELL_ORDER:
    c = by_cell.get(cell, Counter())
    b = sum(c[s] for s in BROWSER)
    px = sum(c[s] for s in PROXY)
    n = sum(c.values())
    tot["have"] += c["have"]; tot["browser"] += b; tot["proxy"] += px; tot["n"] += n
    L.append(f"| `{cell}` | **{c['have']}/{n}** | {b} | {px} | {n} |")
L.append(f"| **total** | **{tot['have']}/{tot['n']}** | {tot['browser']} | {tot['proxy']} "
         f"| {tot['n']} |")

L += ["", "## The gate, stated before anyone starts", "",
      f"Overall retrieval is **{tot['have']}/{tot['n']}**, which is low — but the rate is not the "
      "finding. `BENCHMARK_MEASURED` is at "
      f"**{by_cell['BENCHMARK_MEASURED']['have']}/{sum(by_cell['BENCHMARK_MEASURED'].values())}**, "
      "and that cell is the only place a study measures the parental-household benchmark rather "
      "than proxying it with cohort size. Scope §4 predicted the cell might be empty; the screen "
      "found five; **retrieval has so far returned none of them.**", "",
      "**Extraction does not begin until the five `BENCHMARK_MEASURED` records are resolved one "
      "way or the other.** Not because five records outweigh a hundred, but because a chapter that "
      "reports the reduced-form cells while its identification cell sits unread would be reporting "
      "a literature it did not read — the A.17 failure, where 23/114 was survivable and 0 of 4 "
      "identified direct-arm records was not.", "",
      "## Rung report — probed / found / fetched", "",
      "| rung | probed | found | fetched | |", "|---|---|---|---|---|"]
for rung in ("oa_locations", "repec", "unpaywall", "pmc_bioc"):
    pr = S["probed_per_rung"].get(rung, 0)
    fo = S["found_per_rung"].get(rung, 0)
    fe = S["fetched_per_rung"].get(rung, 0) + S["fetched_per_rung"].get(rung + "+hop", 0)
    note = ("**empty for this literature** — probed and produced no URL at all" if pr and not fo
            else "")
    L.append(f"| `{rung}` | {pr} | {fo} | {fe} | {note} |")
L += ["", "**PMC is empty here, and that was the point of choosing the rung order for this "
      "chapter.** 45 records carry a pmid — demography journals are indexed in PubMed — but not one "
      "is in the PMC open-access subset, so BioC answers HTTP 200 with an empty body every time. "
      "A script that credited the constructed URL as 'found' would report this rung as a broken "
      "downloader rather than an absent corpus. Do not carry this rung into another economics "
      "chapter expecting yield.", ""]

for job, statuses, tool in (
        ("Browser job", BROWSER,
         "These URLs are **open**. They fail to a challenge page (403, or a 202 interstitial, or a "
         "200 with a stub body) or stop at a landing page whose PDF link the script could not "
         "follow. A logged-in browser session retrieves them. **None of these is a paywall** — do "
         "not send them to ILL."),
        ("Proxy job", PROXY,
         "No open copy exists. These need the UChicago proxy, a publisher subscription, or ILL. "
         "Mostly pre-2000 society journals.")):
    rows = [(oid, r) for oid, r in recs.items() if r["status"] in statuses]
    rows.sort(key=lambda kv: (CELL_ORDER.index(kv[1]["cell"])
                              if kv[1]["cell"] in CELL_ORDER else 99, -int(kv[1]["year"] or 0)))
    L += [f"## {job} — {len(rows)} records", "", tool, "",
          "| cell | year | title | doi | status |", "|---|---|---|---|---|"]
    for oid, r in rows:
        L.append(f"| `{r['cell']}` | {r['year']} | {r['title'][:74]} | "
                 f"{r['doi'] or '—'} | {r['status']} |")
    L.append("")

L += ["## When files come back", "",
      "Hand-retrieved PDFs arrive publisher-named. **Check the record's title against the PDF's own "
      "text before installing it** — a wrong pairing corrupts the extraction table silently and "
      "nothing downstream will catch it (`handoff-file-match-by-content`). Install into "
      "`temp/c6a-fulltext/<openalex-id>.pdf` and re-run 313, which is idempotent and will report "
      "the same rung attribution for everything already on disk.", ""]

OUT.write_text("\n".join(L))
print(f"have {tot['have']}/{tot['n']}   browser {tot['browser']}   proxy {tot['proxy']}")
print(f"written: {OUT.name}")
