#!/usr/bin/env python3
"""
239_a23_wall1_ruling.py — A.23. The Wall 1 second read, and the ruling it produces.

The packet `231` assembled was 26 records and three positions, and it said plainly what reading them
could not settle: which chapter *should* own them. That is still true. What the second read changes
is the size of the question, and it changes it by sorting the packet on a field it was never sorted
on.

**THE PACKET WAS ASSEMBLED ON EXPOSURE. IT HAS NEVER BEEN SORTED ON OUTCOME.** Everything where a
price and the living arrangement move together went in, which is the right net to cast for a boundary
dispute and the wrong basis for counting how big the dispute is. Sorted on what each record actually
ESTIMATES, the 26 fall apart: 8 estimate a fertility outcome, 8 estimate nothing at all, 6 have the
ARRANGEMENT as their dependent variable, one estimates a price, one runs in reverse, one cannot be
read. **The contested set is seven studies, not twenty-six**, and three of the eight fertility
records are the identified ones.

That is not a rhetorical simplification. Two of the packet's most-cited members — the JEEA
mortgage-cost paper and Acolin, Lin & Wachter — turn out to have the arrangement as their outcome
and fertility only in their motivation. **No ruling about ownership can make a link-1 record into a
fertility estimate**, so they leave the dispute whichever way the wall is drawn.

Output: literature/search-logs/{slug}-wall1-ruling.md
"""
import json, os
from collections import Counter, defaultdict

SLUG = "co-residence-parents-household-delay"
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
LOGS = os.path.join(ROOT, "literature", "search-logs")
EXTRACT = os.path.join(ROOT, "extraction")
SRC = os.path.join(EXTRACT, f"{SLUG}-wall1-adjudication.json")
OUT_MD = os.path.join(LOGS, f"{SLUG}-wall1-ruling.md")

CLASS_ORDER = ["FERTILITY", "INTENTION", "ARRANGEMENT", "PRICE", "REVERSE", "NO_ESTIMATE",
               "UNRESOLVED"]
CLASS_MEANS = {
    "FERTILITY": "a birth, a parity progression or completed fertility is the dependent variable",
    "INTENTION": "a stated fertility intention — pooled separately under the standing D.3.b rule",
    "ARRANGEMENT": "**the living arrangement is the dependent variable** — link 1 of the chain, "
                   "and not a fertility estimate under any ruling",
    "PRICE": "a price is the estimated object",
    "REVERSE": "fertility acts on housing — the reverse channel, threat 1",
    "NO_ESTIMATE": "framing, typology or policy description; nothing is estimated",
    "UNRESOLVED": "the available record does not support a classification",
}
OWNER_MEANS = {
    "SHARED": "reported by A.23 **and** C.2.c, magnitude claimed alone by neither",
    "LINK1": "A.23's link 1 — mechanism, cross-referenced to C.2.c",
    "THEORY": "theory stream; read, do not pool",
    "ROUTE_OUT": "not evidence about this exposure",
    "C.2.c": "C.2.c's, cleanly",
    "C.3.e": "the income/liquidity hypothesis; a cross-reference here",
    "UNRESOLVED": "named as unresolved rather than assigned",
}


def main():
    d = json.load(open(SRC))
    recs, meta = d["records"], d["meta"]
    by_class = Counter(r["outcome_class"] for r in recs)
    by_owner = Counter(r["owner"] for r in recs)
    groups = defaultdict(list)
    for r in recs:
        groups[r["outcome_class"]].append(r)
    contested = [r for r in recs if r["owner"] == "SHARED"]
    # A version pair is one study, so the study count folds the preprints and the record count
    # does not. Both are reported; conflating them is how a duplicate becomes a second study.
    contested_studies = [r for r in contested if not r.get("duplicate_of")]
    ident_contested = [r for r in contested_studies if r["design"] == "identified"]

    L = [f"# Wall 1 second read and ruling — A.23 × C.2.c", "",
         "**Generated by:** `source/build/goldset/239_a23_wall1_ruling.py` from "
         f"`extraction/{SLUG}-wall1-adjudication.json`", "",
         f"**Ticket:** TICK-075 · **Read:** {meta['run']} · **Reader:** {meta['reader']}", "",
         "## 1. The dispute is a seventh the size it looked", "",
         "`231` assembled 26 records and stated three positions. The packet was built on **exposure** "
         "— everything where a price and the living arrangement move together — which is the right "
         "net for a boundary dispute and the wrong basis for counting one. Sorted on what each "
         "record actually **estimates**, it falls apart:", "",
         "| Outcome estimated | n | What that means |", "|---|---|---|"]
    for k in CLASS_ORDER:
        if by_class.get(k):
            L.append(f"| `{k}` | {by_class[k]} | {CLASS_MEANS[k]} |")
    L += ["", f"**{by_class['NO_ESTIMATE']} of the 26 estimate nothing at all** and "
          f"**{by_class['ARRANGEMENT']} have the arrangement itself as the dependent variable.** "
          "The second group is the important one, and it includes two of the packet's most-cited "
          "members — the JEEA mortgage-cost paper and Acolin, Lin & Wachter. Fertility appears in "
          "their motivation and not in their estimation. **No ruling about ownership can turn a "
          "link-1 record into a fertility estimate**, so they leave the dispute whichever way the "
          "wall is drawn.", "",
          f"What is genuinely contested is **{len(contested)} records — "
          f"{len(contested_studies)} distinct studies**, once the Spanish subsidy's preprint and "
          f"published version are counted once, **of which {len(ident_contested)} are "
          "identified**.", "",
          "## 2. The ruling", "",
          "> **Ruling 3 — shared and non-additive, and the sub-ruling stands. "
          f"(Shravan, {meta['run']}; PI confirmation pending.)**",
          "> Position 3 of the three `231` set out. The records classified `SHARED` below are "
          "reported in both chapters, flagged `MIXED_PRICE_ARRANGEMENT`, and **neither chapter "
          "claims their magnitude alone**. Both demographic-significance sections must say so in "
          "terms, because the failure this prevents is double-counting the same effect in two "
          "chapters of one review.",
          ">",
          "> **Why not strict inheritance (position 1).** It would take the identified core out of "
          "A.23 and leave the chapter reporting that its registered claim has almost no identified "
          "evidence — a conclusion produced by a filing decision rather than by the literature. The "
          "same objection Ruling 1 raised against dropping the extended arm.",
          ">",
          "> **Why not target-based (position 2).** It would give A.23 the identified core outright "
          "and oblige C.2.c — a finished chapter — to hand back records it has already read and "
          "rated. It also requires the review to decide a policy's *target*, which is a claim about "
          "legislative intent and not about variation.",
          ">",
          "> **What makes position 3 cheap here, and this is new.** It was the expensive option when "
          f"the packet looked like 26 contested records. At {len(contested)} it costs both chapters "
          "a shared paragraph and one flag. The measurement that made the ruling easy is the one "
          "`231` did not run.", "",
          "## 3. What the contested records are", ""]
    for r in contested:
        L += [f"**{r['title']}** · `{r['design']}` · {OWNER_MEANS['SHARED']}", "",
              f"  {r['note']}", ""]
    L += ["## 4. The reclassifications this read makes", "",
          "| Record | Was | Is | Why |", "|---|---|---|---|"]
    for r in recs:
        if "RECLASSIFIED BY THIS READ" in r["note"] or r["owner"] == "ROUTE_OUT":
            was = "Wall 1 packet, primary cell"
            is_ = ("link 1 — outcome is the arrangement" if r["owner"] == "LINK1"
                   else "routed out")
            L.append(f"| {r['title'][:58]} | {was} | {is_} | {r['note'][:150]} |")
    L += ["", "## 5. What this read does not settle", "",
          "- **It is one reader, and the same reader who screened.** A consistency read, not a "
          "panel. The standing rule that adversarial re-rating by one rater is not independence "
          "applies to a boundary read exactly as it applies to a GRADE rating.",
          "- **It does not settle who *should* own the contested records**, which is what `231` "
          "said reading them could not do. It settles that the question is smaller, and it takes "
          "the option that costs least on the reduced set.",
          f"- **{by_class.get('UNRESOLVED', 0)} record remains unclassified** and is named rather "
          "than assigned. Two more were classified from a title and a screen note because retrieval "
          "did not reach them, and they are flagged in the source file.",
          "- **The Taiwan PSFD record is the empirical adjudicator and it is observational.** It "
          "puts tenure and the arrangement in one choice set against a birth outcome, so it can "
          "show how the two variables behave together. It cannot show which one causes what.", ""]
    open(OUT_MD, "w").write("\n".join(L) + "\n")
    print(f"26 records; contested {len(contested)} records / {len(contested_studies)} studies; "
          f"identified among contested {len(ident_contested)}")
    print("by outcome:", dict(by_class))
    print("by owner  :", dict(by_owner))
    print(f"-> {os.path.relpath(OUT_MD, ROOT)}")


if __name__ == "__main__":
    main()
