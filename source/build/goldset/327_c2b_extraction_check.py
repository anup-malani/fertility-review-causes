#!/usr/bin/env python3
"""327 — validate C.2.b's extraction table and report what the full-text reads changed. TICK-079.

Three jobs.

**A loud fall-through on `estimator_class`.** An unlisted estimator that silently lands in a default
bucket pools with what it should be separated from (`estimator-class-list-is-a-gate`). Anything not
on the list is reported, not absorbed.

**Stratify before counting poolable.** The >=3 test is applied AFTER stratification on the tags that
make effects different quantities, never to the raw row count
(`stratify-before-counting-poolable`). Strata here are cell x outcome_level x exposure_direction,
because scope §12 forbids pooling across any of them.

**Report what the FULL TEXT changed.** The screen assigns a cell from a title and abstract; the
full-text read is where that becomes a ruling. A cell whose population changes at full text is the
finding, not an embarrassment — `design-is-not-a-property-of-the-title`.

Usage: python3 source/build/goldset/327_c2b_extraction_check.py
"""
import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LOGS = ROOT / "literature" / "search-logs"
EXTR = ROOT / "extraction" / "child-cost-direct-extraction.csv"

REQUIRED = ["exposure_type", "exposure_distance", "exposure_direction", "cost_component",
            "outcome_level", "channel", "estimator_class", "phenomenon_window"]
VOCAB = {
    "exposure_type": {"PRICE_EXOGENOUS", "PRICE_POLICY", "EXPENDITURE_OBSERVED", "PERCEIVED"},
    "exposure_distance": {"PRICE_MEASURED", "PRICE_PROXIED", "EXPENDITURE_ONLY", "NOT_A_COST"},
    "exposure_direction": {"RISE", "FALL"},
    "cost_component": {"SCHOOLING", "HEALTH", "GOODS", "BIRTH_EVENT", "TOTAL_BUNDLE",
                       "OTHER_CHAPTER"},
    "outcome_level": {"REALIZED", "INTENDED", "DESIRED", "NONE"},
    "channel": {"PRICE_OF_CHILD", "MATERNAL_SCHOOLING", "BOTH_UNSEPARATED"},
    # deliberately NOT exhaustive: anything outside it must be reported, never defaulted
    "estimator_class": {"DiD_two_way_FE", "fuzzy_RD", "sharp_RD", "household_panel_FE",
                        "IV_2SLS", "event_study", "RCT_ITT", "RCT_LATE",
                        "time_series_regression_with_simulation"},
}


def main():
    rows = list(csv.DictReader(EXTR.open()))
    problems = []
    for r in rows:
        for k in REQUIRED:
            v = (r.get(k) or "").strip()
            if not v:
                problems.append(f"{r['screen_id']}: `{k}` is empty")
            elif k in VOCAB and v not in VOCAB[k]:
                problems.append(f"{r['screen_id']}: `{k}` = {v!r} is OFF-VOCABULARY "
                                f"— add it deliberately or fix the row")

    L = ["# C.2.b extraction — validation and what the full texts changed", "",
         "Generated by `source/build/goldset/327_c2b_extraction_check.py`. Do not edit by hand.", "",
         f"**{len(rows)} records extracted** from the full text "
         f"({sum(1 for r in rows if not r['routing'].startswith('TWIN'))} distinct "
         "studies; twins counted once).", ""]
    L += ["## Vocabulary check", ""]
    if problems:
        L += ["**Off-vocabulary or missing values — reported, never absorbed into a default:**", ""]
        L += [f"- {p}" for p in problems]
    else:
        L.append("All required tags present and on-vocabulary.")
    L.append("")

    # what changed at full text
    moved = [r for r in rows if r["routing"].startswith(("ROUTE OUT", "RE-CELLED", "BOUNDARY"))]
    L += ["## What the full-text read changed", "",
          f"**{len(moved)} of {len(rows)} studies moved** out of the cell the title/abstract screen "
          "put them in. That is the full-text screen doing its job: a `cell` assigned from an "
          "abstract is a hypothesis (`design-is-not-a-property-of-the-title`).", "",
          "| study | screen cell | after full text | why |", "|---|---|---|---|"]
    for r in moved:
        L.append(f"| {r['study'][:48]} | *(screen)* | `{r['cell_after_fulltext']}` | "
                 f"{r['routing'][:150]} |")
    L += ["", "## Primary cells after the full-text read", "",
          "| cell | studies | consistent with C.2.b | inconsistent | n/a |", "|---|---|---|---|---|"]
    cells = defaultdict(list)
    for r in rows:
        if r["routing"].startswith(("ROUTE OUT", "TWIN")):
            continue
        cells[r["cell_after_fulltext"]].append(r)
    for c, rs in sorted(cells.items()):
        con = sum(1 for r in rs if r["sign_vs_c2b"].startswith("CONSISTENT"))
        inc = sum(1 for r in rs if r["sign_vs_c2b"].startswith("INCONSISTENT"))
        na = len(rs) - con - inc
        L.append(f"| `{c}` | {len(rs)} | {con} | {inc} | {na} |")

    # Which PHENOMENON does the admitted evidence actually bear on? The registry puts C.2.b on FDT
    # AND SDT, and scope §4 warned that transporting an LMIC schooling elasticity to the rich-country
    # SDT is a stronger assumption than GRADE's indirectness domain usually carries. This table is
    # where that warning becomes a count.
    L += ["", "## Which phenomenon does the admitted evidence bear on?", "",
          "| phenomenon | studies | which |", "|---|---|---|"]
    ph = defaultdict(list)
    for r in rows:
        if r["routing"].startswith(("ROUTE OUT", "TWIN")):
            continue
        key = "SDT" if r["phenomenon_window"].startswith("SDT") else \
              "FDT" if r["phenomenon_window"].startswith("FDT") else "PM/FDT-like (LMIC)"
        ph[key].append(r["study"].split(",")[0])
    for k in ("SDT", "FDT", "PM/FDT-like (LMIC)"):
        if ph[k]:
            L.append(f"| **{k}** | {len(ph[k])} | {', '.join(ph[k])} |")
    L += ["", "The registry puts C.2.b on **FDT and SDT**. Scope §4 warned that carrying an LMIC "
          "schooling or health-price elasticity to the rich-country SDT is a stronger assumption "
          "than GRADE's indirectness domain usually carries; this table is where that warning stops "
          "being a worry and becomes a count.", ""]

    L += ["", "## Poolability — stratified FIRST, then counted", "",
          "Scope §12 forbids pooling across `outcome_level`, `exposure_direction` or "
          "`cost_component`, so the >=3 test is applied to the strata and never to the raw row "
          "count (`stratify-before-counting-poolable`).", "",
          "| stratum (cell x outcome_level x direction) | n | poolable (>=3)? |", "|---|---|---|"]
    strata = Counter((r["cell_after_fulltext"], r["outcome_level"], r["exposure_direction"])
                     for r in rows if not r["routing"].startswith(("ROUTE OUT", "TWIN")))
    for k, n in sorted(strata.items()):
        L.append(f"| `{k[0]}` / {k[1]} / {k[2]} | {n} | {'yes' if n >= 3 else '**no**'} |")
    L += ["", f"Largest stratum is **{max(strata.values())}**, so **no meta-analysis is possible** "
          "and PROTOCOL §5 stage 9 resolves to narrative synthesis. Reporting a pooled estimate "
          "across these strata would average a realized-fertility elasticity against a "
          "desired-fertility one and a price rise against a price fall.", ""]
    # ---- risk of bias, folded into the same report so the two are never read apart
    rob_p = ROOT / "extraction" / "child-cost-direct-risk-of-bias.csv"
    if rob_p.exists():
        rob = list(csv.DictReader(rob_p.open()))
        L += ["## Risk of bias", "",
              "Domains are scope §11's named threats, not a generic checklist. `D3` is the one that "
              "does the work here: it asks whether the PRICE channel is separated from the "
              "neighbouring mechanism, and it is where three of six studies lose their weight.", "",
              "| study | D1 price | D2 exog. | D3 channel | D5 outcome | D6 transport | overall |",
              "|---|---|---|---|---|---|---|"]
        def g(v):
            return v.split(" —")[0].split(";")[0].strip()
        for r in rob:
            L.append(f"| {r['study'][:38]} | {g(r['D1_price_not_expenditure'])} | "
                     f"{g(r['D2_exogeneity'])} | {g(r['D3_channel_separation'])} | "
                     f"{g(r['D5_outcome_measurement'])} | "
                     f"{g(r['D6_transport_to_registered_phenomenon'])} | **{r['overall']}** |")
        L += ["", "Reasons:", ""]
        L += [f"- **{r['study'][:44]}** — {r['overall_reason']}" for r in rob]
        L.append("")
        clean = [r for r in rob if r["overall"].startswith(("LOW", "MODERATE"))]
        L += ["", f"**{len(clean)} of {len(rob)} studies are MODERATE or better**, and none is LOW. "
              "The chapter has no low-risk estimate of its own parameter.", ""]

    (LOGS / "child-cost-direct-extraction-check.md").write_text("\n".join(L))
    print("\n".join(L))


main()
