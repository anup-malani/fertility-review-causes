#!/usr/bin/env python3
"""325 — rank C.2.b's outstanding retrievals by what they can still CHANGE (TICK-079).

A retrieval queue ordered by tier alone says "get the primary cell first" and stops there. The useful
question is narrower: which missing full texts could move a cell from populated to empty, settle an
open ruling, or promote a boundary record into the primary cell? Those go first, because they are the
ones whose absence makes the chapter unwritable rather than merely thinner.

Bands, and what each is for:

  P0  the retrieval decides whether a CELL EXISTS. Either it is the only uncovered record in a
      thinly-populated primary cell, or it is one of the few records carrying a direction or a
      channel the chapter's rulings turn on.
  P1  the remaining uncovered PRIMARY studies. They thicken a cell that already exists.
  P2  boundary records whose scope-16.2 `channel` ruling could PROMOTE them into the primary cell --
      or, read the other way, could empty it.
  P3  context: price- and expenditure-association records, and the measurement literature.

`band-rules-must-read-screen-notes`: the band keys off the screen NOTE first, not the cell, because
the reason a record matters is in the note. C.3.g's cell-keyed P0 buried its only identified estimate
in P3.

Usage: python3 source/build/goldset/325_c2b_retrieval_priority.py
"""
import csv
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LOGS = ROOT / "literature" / "search-logs"
PRIMARY_CELLS = {"PRICE_SHOCK_FERTILITY", "SCHOOL_COST_FERTILITY",
                 "CHILD_HEALTH_COST_FERTILITY", "BIRTH_EVENT_COST"}
GOT = {"fetched", "already_on_disk", "covered_by_twin", "hand_retrieved"}


def fold(t):
    return re.sub(r"[^a-z0-9]+", " ", (t or "").lower()).strip()[:60]


def main():
    ret = json.loads((LOGS / "child-cost-direct-retrieval.json").read_text())["records"]
    verd = {r["screen_id"]: r for r in
            csv.DictReader((ROOT / "extraction" /
                            "child-cost-direct-screen-verdicts.csv").open())}
    for r in ret:
        r["note"] = (verd.get(r["screen_id"]) or {}).get("note", "")

    # group to studies; a study is covered if ANY of its records was retrieved
    studies = defaultdict(list)
    for r in ret:
        studies[fold(r["title"])].append(r)
    covered = {k for k, v in studies.items() if any(x["status"] in GOT for x in v)}

    # how thin is each primary cell once you count only COVERED studies?
    cell_state = defaultdict(lambda: {"covered": 0, "uncovered": 0})
    for k, v in studies.items():
        cell = v[0]["cell"]
        cell_state[cell]["covered" if k in covered else "uncovered"] += 1

    NOTE_RISE = re.compile(r"REINTRODUCTION|termination|emancipation|RISE", re.I)
    NOTE_CHANNEL = re.compile(r"MATERNAL_SCHOOLING|BOTH_UNSEPARATED|channel", re.I)

    rows = []
    for k, v in studies.items():
        if k in covered:
            continue
        r = sorted(v, key=lambda x: x["tier"])[0]
        cell, note, tier = r["cell"], r["note"], r["tier"]
        reasons = []
        if tier == 1 and cell in PRIMARY_CELLS and cell_state[cell]["covered"] == 0:
            reasons.append(f"**no study in `{cell}` has been retrieved at all** — this cell is "
                           "currently unevidenced")
        if NOTE_RISE.search(note):
            reasons.append("carries the **RISE direction** scope §4 says is nearly absent; settles "
                           "PI Call 3 on the symmetry assumption")
        if NOTE_CHANNEL.search(note):
            reasons.append("§16.2 **channel ruling** — price-of-child vs maternal schooling cannot "
                           "be told without the full text")
        band = ("P0" if (reasons and tier == 1) else
                "P1" if tier == 1 else
                "P2" if (tier == 2 and NOTE_CHANNEL.search(note)) else
                "P2" if tier == 2 else "P3")
        rows.append({"band": band, "id": r["screen_id"], "tier": tier, "cell": cell,
                     "job": r.get("handoff"), "year": r.get("year"), "doi": r.get("doi"),
                     "title": r.get("title"), "why": reasons, "note": note})
    rows.sort(key=lambda r: (r["band"], r["tier"], r["id"]))

    L = ["# C.2.b — outstanding retrievals, ranked by what they can change", "",
         "Generated by `source/build/goldset/325_c2b_retrieval_priority.py`. Do not edit by hand.",
         "",
         f"**{len(studies) - len(covered)} of {len(studies)} studies still missing.** Ordered by "
         "what the full text could still decide, not by tier alone. The band keys off the screen "
         "NOTE before the cell (`band-rules-must-read-screen-notes`).", "",
         "## Primary-cell state — covered vs uncovered STUDIES", "",
         "A cell with zero covered studies is currently unevidenced no matter how many records the "
         "screen put in it.", "",
         "| cell | covered | uncovered |", "|---|---|---|"]
    for c in sorted(PRIMARY_CELLS):
        st = cell_state[c]
        flag = "  ← **unevidenced**" if st["covered"] == 0 and st["uncovered"] else ""
        L.append(f"| `{c}` | {st['covered']} | {st['uncovered']}{flag} |")
    L += ["", "## The queue", ""]
    for band, blurb in (("P0", "decides whether a cell exists, or settles an open ruling"),
                        ("P1", "remaining primary-cell studies"),
                        ("P2", "boundary records whose channel ruling could promote them"),
                        ("P3", "context")):
        grp = [r for r in rows if r["band"] == band]
        if not grp:
            continue
        L += [f"### {band} — {blurb} ({len(grp)})", "",
              "| id | job | cell | year | DOI | title |", "|---|---|---|---|---|---|"]
        for r in grp:
            L.append(f"| {r['id']} | `{r['job']}` | `{r['cell']}` | {r['year'] or ''} | "
                     f"{r['doi'] or ''} | {(r['title'] or '')[:58]} |")
        L.append("")
        if band in ("P0", "P2"):
            for r in grp:
                if r["why"]:
                    L.append(f"- **{r['id']}** — " + "; ".join(r["why"]))
            L.append("")
    L += ["## Job mix in the queue", "",
          "| band | proxy | browser |", "|---|---|---|"]
    for band in ("P0", "P1", "P2", "P3"):
        c = Counter(r["job"] for r in rows if r["band"] == band)
        if sum(c.values()):
            L.append(f"| {band} | {c['proxy']} | {c['browser']} |")
    L.append("")
    (LOGS / "child-cost-direct-retrieval-priority.md").write_text("\n".join(L))
    print("\n".join(L))


main()
