#!/usr/bin/env python3
"""
388 — C.3.f: the depth probe's yield curve, generated from the verdicts.

`generate-result-tables-never-retype`. Every number in the probe write-up comes from here.

The question the probe exists to answer is whether the 4,181-record universe can be truncated.
`a-flat-yield-curve-forbids-truncation` says a flat curve forbids it, because the best record may
sit in the last stratum. This curve is not flat and it is not declining either.

Output literature/search-logs/c3f-probe-summary-<date>.md.
"""
import csv, collections, datetime, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
V = ROOT / "extraction" / "wealth-flows-reversal-screen-verdicts.csv"
LOGS = ROOT / "literature" / "search-logs"
DATE = datetime.date.today().isoformat()

PRIMARY = {"NET_FLOW_FERTILITY", "SHOCK_NET_FERTILITY"}
IN_SCOPE = PRIMARY | {"UPWARD_COMPONENT", "DOWNWARD_COMPONENT", "FLOW_MEASUREMENT",
                      "FLOW_ASSOCIATION"}


def main():
    rows = list(csv.DictReader(V.open()))
    strata = sorted({r["batch"] for r in rows if r["batch"].startswith("probe-s")})
    lines = [f"# C.3.f depth probe — yield curve — {DATE}", "",
             "Generated by `source/build/goldset/388_c3f_probe_summary.py` from",
             "`extraction/wealth-flows-reversal-screen-verdicts.csv`. Do not edit by hand.", "",
             "Strata are evenly spaced by citation rank over the 4,181-record universe: stratum 1 is",
             "the most-cited head, stratum 8 the uncited tail.", "",
             "| stratum | n | primary | in scope | uncertain |", "|---|---|---|---|---|"]
    for b in strata:
        s = [r for r in rows if r["batch"] == b]
        lines.append(f"| {b.replace('probe-', '')} | {len(s)} | "
                     f"{sum(1 for r in s if r['cell'] in PRIMARY)} | "
                     f"{sum(1 for r in s if r['cell'] in IN_SCOPE)} | "
                     f"{sum(1 for r in s if r['confidence'] == 'UNCERTAIN')} |")
    tot = [r for r in rows if r["batch"].startswith("probe-s")]
    lines.append(f"| **total** | **{len(tot)}** | "
                 f"**{sum(1 for r in tot if r['cell'] in PRIMARY)}** | "
                 f"**{sum(1 for r in tot if r['cell'] in IN_SCOPE)}** | "
                 f"**{sum(1 for r in tot if r['confidence'] == 'UNCERTAIN')}** |")

    prim = [r for r in tot if r["cell"] in PRIMARY]
    lines += ["", "## Every primary record found, and where it sat", "",
              "| screen id | stratum | cell | identified | note |", "|---|---|---|---|---|"]
    lines += [f"| `{r['screen_id']}` | {r['batch'].replace('probe-', '')} | {r['cell']} | "
              f"{r['identified']} | {r['note']} |" for r in prim]

    cells = collections.Counter(r["cell"] for r in tot)
    lines += ["", "## Cells", "", "| cell | n |", "|---|---|"]
    lines += [f"| `{c}` | {n} |" for c, n in cells.most_common()]

    lines += ["", "## Can the universe be truncated?", "", "**No, and the reason is stronger than "
              "the usual one.**", "",
              "`a-flat-yield-curve-forbids-truncation` forbids truncation when the curve is flat,",
              "because the best record may sit in the last stratum. This curve is not flat: primary",
              "yield is **zero across the four most-cited strata** and every primary record found",
              "sits in the uncited region. Truncating anywhere near the head would have returned an",
              "evidence base of zero and reported it as the literature.", ""]
    (LOGS / f"c3f-probe-summary-{DATE}.md").write_text("\n".join(lines))
    print("\n".join(lines[:22]))
    print(f"\nwrote c3f-probe-summary-{DATE}.md")


main()
