#!/usr/bin/env python3
"""
197_a17_demographic_significance.py — A.17, stage 10. The SDT arithmetic, computed not asserted.

**SDT ONLY.** ART does not exist before 1978 and is demographically negligible before the mid-1990s,
so PM and FDT are not unsupported here — they are outside the technology's existence. The chapter
says that rather than rating an absence.

THE ORDER OF OPERATIONS IS THE TEMPLATE'S §2.4 AND IT IS NOT NEGOTIABLE.

  1. **The units check (S4) comes before any arithmetic.** The phenomenon is measured in whole
     children per woman; the mechanism offers a share of births currently running between roughly 1%
     and 7%. Those are two orders of magnitude apart, and on A.12 that observation settled the
     question before any estimate existed. It does not settle it here — a few percent of a TFR is
     not nothing when the decline itself is around one child — so this chapter has to do the
     arithmetic that A.12 could skip.

  2. **Decomposition share per country**, shown inline so a reader can check it:
        TFR_without = TFR_observed x (1 - s),  s = ART/MAR share of the TFR
        offset      = (TFR_observed - TFR_without) / (TFR_baseline - TFR_without)
     i.e. what fraction of the observed SDT decline is undone by ART, holding everything else fixed.

  3. **The endogeneity check.** Does the mechanism's own movement come from the phenomenon it is
     claimed to offset? A.12 found a quarter of the modern twinning rise was driven by the very
     postponement it claimed to offset, and had to net it out. **The same feedback runs here and it
     is larger, not smaller**: ART demand is generated by postponement. The share is therefore not
     an independent force acting against the decline; part of it is a consequence of the decline. The
     script reports the uncorrected offset and states the direction of the correction, because no
     study in hand quantifies the split.

  4. **Every number here is an UPPER BOUND**, for the reason stage 6 established: 9 of 14 arm-1
     records in hand compute the contribution without confronting the counterfactual, so the shares
     they report treat every ART birth as one that would not otherwise have occurred.

BASELINE YEAR. The SDT is dated from ~1965 in PROTOCOL. World Bank TFR series are used because they
are free, versioned, and reproducible without a key; the retrieved papers' own shares are used for
the mechanism because they are the measurement under review. Where a paper reports the
with-and-without TFR directly (Czechia), that pair is used in preference to the script's own
reconstruction, and both are printed so the difference is visible.

Output: literature/search-logs/{slug}-demographic-significance.md
        extraction/{slug}-demsig.json
"""
import json, os, subprocess, sys

SLUG = "art-access-fertility-recovery"
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
LOGS = os.path.join(ROOT, "literature", "search-logs")
EXTRACT = os.path.join(ROOT, "extraction")
OUT_MD = os.path.join(LOGS, f"{SLUG}-demographic-significance.md")
OUT_JSON = os.path.join(EXTRACT, f"{SLUG}-demsig.json")

SDT_BASE_YEAR = 1965

# Shares taken from the retrieved full texts. `share_of` records WHAT the share is a share of, because
# a share of BIRTHS and a share of the TFR are not the same quantity and conflating them is the
# denominator error A.12 warned about.
CASES = [
    dict(iso="CZE", country="Czechia", year=2020, share=0.034, share_of="TFR",
         src="Scientific Reports 2023 (W4383264299)",
         reported_pair=(1.71, 1.65),
         note="The paper reports the with/without pair directly. Its TFR_nonART series is built by "
              "pure subtraction, and it concedes without quantifying that some ART-attributed births "
              "would have occurred anyway."),
    dict(iso="ITA", country="Italy", year=2023, share=0.039, share_of="TFR",
         src="PLoS ONE 2026 (W7169859806); Human Reproduction 2025 (W4412170497) gives 3.7% for 2022",
         reported_pair=None,
         note="Projected to stay essentially flat to 2050 (3.9% to 4.3%), which is evidence against "
              "v5's clause that the contribution is growing."),
    dict(iso="AUS", country="Australia", year=2017, share=0.067, share_of="births",
         src="Human Reproduction 2022 (W4213230270)",
         reported_pair=None,
         note="Splits as 4.8% ART and 1.9% ovulation induction. The OI half is invisible to ART "
              "registries, so registry-based shares understate MAR."),
    dict(iso="DNK", country="Denmark", year=2004, share=0.042, share_of="births",
         src="quoted in Bitler & Schmidt NBER 2011 (W2058178715) from Nyboe Andersen et al. 2008",
         reported_pair=None,
         note="The highest national share in the frame for its period, and the contrast with the "
              "contemporaneous US figure of ~1.2% is the clearest single illustration that access "
              "regimes move the share by a factor of three."),
    dict(iso="USA", country="United States", year=2019, share=0.0197, share_of="births",
         src="Vital Statistics via PRPR 2024 (W4390964890); SART counts run higher",
         reported_pair=None,
         note="The two US series disagree. The lower Vital Statistics figure is used, and the "
              "disagreement is itself a measurement finding."),
]


def wb_tfr(iso, year):
    url = (f"https://api.worldbank.org/v2/country/{iso}/indicator/SP.DYN.TFRT.IN"
           f"?date={year}:{year}&format=json&per_page=10")
    try:
        r = subprocess.run(["curl", "-s", "-m", "40", url], capture_output=True, text=True)
        d = json.loads(r.stdout)
        for row in (d[1] or []):
            if row.get("value") is not None:
                return round(float(row["value"]), 3)
    except Exception:
        return None
    return None


def band(x):
    if x is None:
        return "NOT ASSESSED"
    a = abs(x)
    return ("NEGLIGIBLE" if a < 0.05 else "MINOR" if a < 0.20 else
            "SUBSTANTIAL" if a < 0.50 else "DOMINANT")


def main():
    out = []
    for c in CASES:
        base = wb_tfr(c["iso"], SDT_BASE_YEAR)
        obs = wb_tfr(c["iso"], c["year"])
        if base is None or obs is None:
            out.append(dict(c, error="World Bank TFR unavailable — UNCONFIRMED, not zero"))
            continue
        # A share OF BIRTHS applies to the TFR only under the (standard, stated) assumption that the
        # ART share is the same across the age schedule. That assumption is false — ART is
        # concentrated at older ages — and it biases the implied TFR contribution UPWARD relative to
        # a share of the TFR proper. Both are reported so the reader can see which is which.
        s = c["share"]
        without = round(obs * (1 - s), 3)
        contrib = round(obs - without, 3)
        decline_without = round(base - without, 3)
        offset = round(contrib / decline_without, 4) if decline_without > 0 else None
        rec = dict(c, tfr_base=base, tfr_obs=obs, tfr_without=without,
                   contribution=contrib, decline_without_art=decline_without,
                   offset_share=offset, verdict=band(offset))
        if c.get("reported_pair"):
            po, pw = c["reported_pair"]
            rec["paper_contribution"] = round(po - pw, 3)
            rec["paper_offset_share"] = round((po - pw) / (base - pw), 4) if base > pw else None
        out.append(rec)
    json.dump(out, open(OUT_JSON, "w"), indent=2)

    ok = [r for r in out if "error" not in r]
    offs = [r["offset_share"] for r in ok if r["offset_share"] is not None]
    lo, hi = (min(offs), max(offs)) if offs else (None, None)
    pc = lambda x: f"{x:.1%}" if x is not None else "n/a"

    L = [f"# Stage 10 demographic significance — {SLUG} (A.17)", "",
         "> **PROVISIONAL: computed on 33 of 131 wanted full texts.** Every share below is an UPPER "
         "BOUND, because 9 of the 14 arm-1 records in hand compute ART's contribution without "
         "confronting the counterfactual — they treat every ART birth as one that would not "
         "otherwise have occurred.", "",
         "## PM and FDT", "",
         "**NOT ASSESSED, and not for lack of evidence.** The first IVF birth was in 1978 and ART is "
         "demographically negligible before the mid-1990s. Pre-modern and First-Demographic-"
         "Transition fertility cannot be affected by a technology that does not exist. If it had "
         "existed the sign would be positive; the registry does not enumerate these arms and this "
         "chapter does not invent them.", "",
         "## S4 — the units check, before any arithmetic", "",
         "**The phenomenon to be explained is measured in whole children per woman; this mechanism "
         "offers a share of births running between about 1% and 7%.**", "",
         "On A.12 a units check of this shape ended the chapter: a multiplier bounded between 1.01 "
         "and 1.05 cannot explain a phenomenon denominated in whole children, and no study could "
         "have changed that. **It does not end this one.** A few percent of a TFR is not nothing "
         "when the decline to be explained is around one child, so A.17 has to do the arithmetic "
         "A.12 could skip. That is the difference between a mechanism that is the wrong size and a "
         "mechanism that is merely small.", "",
         "## The decomposition, per country", "",
         "For each country: `TFR_without = TFR_observed x (1 - s)`, and the offset share is the "
         f"contribution divided by the decline that would have occurred without ART, from a {SDT_BASE_YEAR} "
         "baseline. TFR values are World Bank `SP.DYN.TFRT.IN`; shares are from the retrieved full "
         "texts.", "",
         f"| country | year | share | of | TFR {SDT_BASE_YEAR} | TFR obs | TFR without | contribution | decline without | **offset** | verdict |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in out:
        if "error" in r:
            L.append(f"| {r['country']} | {r['year']} | — | — | — | — | — | — | — | **UNCONFIRMED** | NOT ASSESSED |")
            continue
        L.append(f"| {r['country']} | {r['year']} | {r['share']:.1%} | {r['share_of']} | "
                 f"{r['tfr_base']} | {r['tfr_obs']} | {r['tfr_without']} | +{r['contribution']} | "
                 f"{r['decline_without_art']} | **{pc(r['offset_share'])}** | {r['verdict']} |")
    L += ["",
          f"**Range across the five settings: {pc(lo)} to {pc(hi)}.**", ""]
    cz = next((r for r in ok if r["iso"] == "CZE"), None)
    if cz and cz.get("paper_offset_share") is not None:
        L += ["### Check against the one paper that reports the pair itself", "",
              f"Czechia is the only case where a retrieved paper states the with-and-without TFR "
              f"directly: **{cz['reported_pair'][0]} with ART against {cz['reported_pair'][1]} "
              f"without**, a contribution of {cz['paper_contribution']} children. Against the "
              f"{SDT_BASE_YEAR} baseline of {cz['tfr_base']} that is an offset of "
              f"**{pc(cz['paper_offset_share'])}**, against this script's reconstruction of "
              f"{pc(cz['offset_share'])}. The two agree closely, which is the point of running both.", ""]
    L += ["## A denominator warning the arithmetic above cannot fix", "",
          "Three of the five shares are shares **of births**; two are shares **of the TFR**. They are "
          "not the same quantity. Converting a birth share into a TFR contribution assumes the ART "
          "share is constant across the age schedule, and it is not — **ART is concentrated at older "
          "ages**, where age-specific fertility rates are low. The Italian data make this visible: "
          "MAR is 3.7% of the TFR overall and **16% among the oldest mothers**. Applying a flat "
          "birth share therefore biases the implied contribution UPWARD, in the same direction as "
          "the counterfactual error. Both errors inflate; neither offsets the other.", "",
          "## The endogeneity check, which is the largest correction and is unquantified", "",
          "**ART demand is generated by postponement.** The mechanism's own movement is caused, in "
          "substantial part, by the phenomenon it is claimed to offset: women seek treatment because "
          "they began later. A.12 met the same structure — a quarter of the modern twinning rise is "
          "driven by delayed childbearing — and had to net it out before claiming any offset. **The "
          "feedback is larger here, not smaller**, because A.12's channel was compositional while "
          "this one is the whole demand mechanism.", "",
          "A component of the offset that exists only because the decline occurred is not evidence "
          "against the decline's cause. **No study in hand decomposes the share into an "
          "induced-by-postponement part and an independent part**, so the correction's magnitude is "
          "unknown and its direction is not: it reduces every figure in the table above.", "",
          "## S5 — the verdict sentence", "", ]
    # The SDT verdict takes the band of the range's upper end, since the numbers are upper bounds.
    top = band(hi)
    L += [f"**For the Second Demographic Transition, the verdict is {top}, because ART's contribution "
          f"to the TFR runs between {pc(lo)} and {pc(hi)} of the observed decline across the five "
          "settings measured, and every one of those figures is an upper bound before the "
          "counterfactual and postponement-feedback corrections are applied.**", "",
          "**For pre-modern variation, the verdict is NOT ASSESSED, because the technology did not "
          "exist.**", "",
          "**For the First Demographic Transition, the verdict is NOT ASSESSED, because the "
          "technology did not exist.**", ""]
    open(OUT_MD, "w").write("\n".join(L) + "\n")
    print(f"cases={len(out)} offsets={[pc(r.get('offset_share')) for r in ok]}")
    print(f"range={pc(lo)}-{pc(hi)}  SDT verdict={top}")
    print(f"-> {os.path.relpath(OUT_MD, ROOT)}")


if __name__ == "__main__":
    main()
