#!/usr/bin/env python3
"""323 — score C.2.b's depth probe: yield by stratum, and sensitivity against the withheld gold.

Two things the screen cannot tell you about itself:

**Where the yield is.** Screening front-to-back reports the head as if it were the population
(`citation-sorted-head-is-not-the-population`). The probe took evenly spaced strata, so the yield
curve here is the whole universe's, and it says whether a truncated screen would have been safe.

**Whether the screen catches what it should.** Gold flags were withheld from the batches; they are
merged here, after the fact. Sensitivity is computed only over rows that actually carry a verdict —
a positives-only screen cannot measure its own (`a-positives-only-screen-cannot-measure-sensitivity`),
so a gold row with no verdict is reported as UNSCREENED and never counted as a miss or a catch.

Usage: python3 source/build/goldset/323_c2b_score_probe.py
"""
import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LOGS = ROOT / "literature" / "search-logs"
EXTR = ROOT / "extraction"
BATCH = EXTR / "child-cost-direct-screen-batches"
CAUGHT = {"INCLUDE_PRIMARY", "INCLUDE_CONTEXT", "BOUNDARY"}


def main():
    uni = json.loads((LOGS / "child-cost-direct-screen-universe.json").read_text())["records"]
    for i, r in enumerate(uni):
        r["screen_id"] = f"C2B{i:04d}"
    by_id = {r["screen_id"]: r for r in uni}
    gold_blob = json.loads((LOGS / "child-cost-direct-screen-gold.json").read_text())
    gold_by_oa = {k: v for k, v in gold_blob["gold"].items() if v.get("is_gold")}
    gold_ids = {r["screen_id"] for r in uni if r.get("oa_id") in gold_by_oa}

    verdicts = {}
    with (EXTR / "child-cost-direct-screen-verdicts.csv").open() as f:
        for row in csv.DictReader(f):
            verdicts[row["screen_id"]] = row

    strata = {}
    for f in sorted(BATCH.glob("probe-s*.json")):
        d = json.loads(f.read_text())
        strata[d["name"]] = [r["screen_id"] for r in d["records"]]

    L = ["# C.2.b depth probe — yield by stratum and screen sensitivity", "",
         "Generated by `source/build/goldset/323_c2b_score_probe.py`. Do not edit by hand.", "",
         "## Yield by stratum", "",
         "Strata are evenly spaced across the citation-ranked universe, so this is the shape of the "
         "whole pool rather than of its head (`citation-sorted-head-is-not-the-population`).", "",
         "| stratum | n | primary | context | boundary | routed | excluded | insufficient |",
         "|---|---|---|---|---|---|---|---|"]
    totals = Counter()
    for name, ids in strata.items():
        c = Counter(verdicts[i]["verdict"] for i in ids if i in verdicts)
        totals.update(c)
        L.append(f"| `{name}` | {len(ids)} | **{c['INCLUDE_PRIMARY']}** | {c['INCLUDE_CONTEXT']} | "
                 f"{c['BOUNDARY']} | {c['ROUTED_OTHER']} | {c['EXCLUDE']} | "
                 f"{c['INSUFFICIENT_INFO']} |")
    n = sum(len(v) for v in strata.values())
    L.append(f"| **all** | **{n}** | **{totals['INCLUDE_PRIMARY']}** | {totals['INCLUDE_CONTEXT']} "
             f"| {totals['BOUNDARY']} | {totals['ROUTED_OTHER']} | {totals['EXCLUDE']} | "
             f"{totals['INSUFFICIENT_INFO']} |")

    # `bound-what-you-did-not-screen`: a sample needs a prevalence AND an interval, or the unscreened
    # remainder gets reported as though it were known. Wilson interval, which behaves at small p.
    import math
    k, N = totals["INCLUDE_PRIMARY"], n
    tot = len(uni)
    z = 1.96
    ph = k / N
    den = 1 + z * z / N
    ctr = (ph + z * z / (2 * N)) / den
    hw = z * math.sqrt(ph * (1 - ph) / N + z * z / (4 * N * N)) / den
    lo, hi = max(0.0, ctr - hw), min(1.0, ctr + hw)
    yields = [Counter(verdicts[i]["verdict"] for i in ids if i in verdicts)["INCLUDE_PRIMARY"]
              for ids in strata.values()]
    flat = max(yields) - min(yields) <= 2
    L += ["", "## What the unscreened remainder implies", "",
          f"Primary-cell prevalence in the probe: **{k}/{N} = {100 * ph:.1f}%** "
          f"(Wilson 95% CI {100 * lo:.1f}%–{100 * hi:.1f}%). Applied to the {tot}-record universe "
          f"that is **{lo * tot:.0f}–{hi * tot:.0f} primary records**, point estimate "
          f"**{ph * tot:.0f}**. Reported as an interval because the remainder is unscreened and a "
          "point estimate would read as a count (`bound-what-you-did-not-screen`).", "",
          f"Per-stratum primary counts, head to tail: **{yields}**."]
    if flat:
        L += ["", "**The yield curve is flat, and that is the operationally important result.** "
              "A.18's strata ran 53% / 9.1% / 3.3% / 0.7% and a truncated screen there would have "
              "cost little. Here the tail carries as much as the head — the single cleanest "
              "primary record in the probe sits in the LAST stratum — so **this screen cannot be "
              "truncated**, and a citation-ordered partial pass would have found neither the "
              "kibbutz privatisation nor the Ghana scholarship RCT."]
    L += ["", "## Cells", "", "| cell | n |", "|---|---|"]
    L += [f"| `{k or '(none)'}` | {v} |"
          for k, v in Counter(v["cell"] for v in verdicts.values()).most_common()]

    scored = gold_ids & set(verdicts)
    unscreened = gold_ids - set(verdicts)
    caught = [i for i in scored if verdicts[i]["verdict"] in CAUGHT]
    missed = [i for i in scored if verdicts[i]["verdict"] not in CAUGHT]
    L += ["", "## Sensitivity against the withheld gold", "",
          f"The universe holds **{len(gold_ids)}** gold records. The probe touched **{len(scored)}** "
          f"of them; the other **{len(unscreened)}** are UNSCREENED and are counted neither as a "
          "catch nor as a miss.", ""]
    if scored:
        L.append(f"**Sensitivity on screened gold: {len(caught)}/{len(scored)} = "
                 f"{100 * len(caught) / len(scored):.0f}%**")
    L += ["", "| gold record | verdict | cell |", "|---|---|---|"]
    for i in sorted(scored):
        L.append(f"| {by_id[i]['title'][:66]} | `{verdicts[i]['verdict']}` | "
                 f"`{verdicts[i]['cell']}` |")
    if missed:
        L += ["", "**Missed gold — read these before trusting the rubric:**", ""]
        L += [f"- {by_id[i]['title'][:80]} — {verdicts[i]['note']}" for i in sorted(missed)]

    # ------------------------------------------------------------------ full pass vs the probe
    done = len(verdicts)
    if done >= len(uni):
        k, N = totals["INCLUDE_PRIMARY"], sum(len(v) for v in strata.values())
        actual = sum(1 for v in verdicts.values() if v["verdict"] == "INCLUDE_PRIMARY")
        L += ["", "## The probe's extrapolation against the completed pass", "",
              f"The probe screened {N} records, found **{k}** primary, and projected "
              f"**{lo * tot:.0f}-{hi * tot:.0f}** for the universe (point {ph * tot:.0f}). The "
              f"completed pass over all {done} records found **{actual}**.", "",
              ("**Inside the interval.** The spaced-strata design estimated the whole pool from 14% "
               "of it, which is the case for running a probe before committing to a full screen — "
               "and, here, for not truncating after one."
               if lo * tot <= actual <= hi * tot else
               "**OUTSIDE the interval.** The probe's design did not represent the pool; treat any "
               "future extrapolation from spaced strata on this chapter as unvalidated.")]

    # Version twins are one study (`version-pair-is-one-study`). A count of primary RECORDS
    # overstates the evidence base whenever a working paper and its journal version both survive.
    import re as _re
    def fold(t):
        return _re.sub(r"[^a-z0-9]+", " ", (t or "").lower()).strip()
    prim = [i for i in verdicts if verdicts[i]["verdict"] == "INCLUDE_PRIMARY"]
    groups = {}
    for i in prim:
        groups.setdefault(fold(by_id[i]["title"])[:60], []).append(i)
    L += ["", "## Primary records vs primary STUDIES", "",
          f"**{len(prim)} primary records** collapse to **{len(groups)} distinct studies** once "
          "version twins are grouped on folded title. A count of records overstates the evidence "
          "base whenever a working paper and its journal version both survive "
          "(`version-pair-is-one-study`).", ""]
    for key, ids in sorted(groups.items(), key=lambda kv: -len(kv[1])):
        L.append(f"- **{by_id[ids[0]]['title'][:74]}** — {len(ids)} record(s), "
                 f"`{verdicts[ids[0]]['cell']}`")
    L.append("")
    L += ["", "## Every primary-cell record the probe found", "",
          "| id | title | cell | note |", "|---|---|---|---|"]
    for i in sorted(prim):
        L.append(f"| {i} | {by_id[i]['title'][:56]} | `{verdicts[i]['cell']}` | "
                 f"{verdicts[i]['note'][:88]} |")
    L.append("")
    (LOGS / "child-cost-direct-probe-score.md").write_text("\n".join(L))
    print("\n".join(L))


main()
