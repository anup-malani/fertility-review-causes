#!/usr/bin/env python3
"""
209_c3g_library_wantlist.py — C.3.g, stage 5c. Split the retrieval failures into two handoffs.

**A BLOCKED ROUTE IS NOT A PAYWALL, AND THE TWO GO TO DIFFERENT PEOPLE.** On A.17, 67 of 98 failures
were open URLs killed by bot defence — putting them in front of a human with a library proxy wastes
that human's time, because the proxy is not what is missing. This chapter met the same thing before
the fetch even ran: WUSTL Open Scholarship and SAGE both returned 403 to curl on OPEN-ACCESS content
while the landing page served the whole abstract.

  BROWSER-JOB — the fetcher saw a 200 with an HTML body, or a 403 from a host OpenAlex calls open.
                The content is free; a script cannot have it. Someone opens the URL in a browser and
                saves the PDF. No institutional access needed, and the URL list is directly usable.

  PROXY-JOB   — no open location exists anywhere. A genuinely closed paper. Needs the UChicago
                proxy or an ILL request, and needs a person with credentials.

  NO-ROUTE    — no DOI and no open location: nothing to hand anyone. These need a title search by a
                human, and they are listed separately so they are not silently folded into the proxy
                pile where they would look like paywalls.

Each list is ordered by JOB, so whoever picks it up does J1 (the registered estimand) first. A
retrieval queue ordered by convenience retrieves the easy records; ordered by role, it retrieves the
ones the chapter cannot be written without.

Output: extraction/{slug}-browser-job.txt
        extraction/{slug}-proxy-job.txt
        literature/search-logs/{slug}-library-wantlist.md
"""
import csv, json, os
from collections import Counter, defaultdict

SLUG = "student-debt-household-formation"
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
LOGS = os.path.join(ROOT, "literature", "search-logs")
EXTRACT = os.path.join(ROOT, "extraction")
FETCH = os.path.join(LOGS, f"{SLUG}-fetch-log.csv")
OA = os.path.join(EXTRACT, f"{SLUG}-oa-status.json")
OUT_BROWSER = os.path.join(EXTRACT, f"{SLUG}-browser-job.txt")
OUT_PROXY = os.path.join(EXTRACT, f"{SLUG}-proxy-job.txt")
OUT_MD = os.path.join(LOGS, f"{SLUG}-library-wantlist.md")

JOB_ORDER = ["J1_DIRECT_ARM", "J2_DECISIVE_TITLE_ONLY", "J3_IDENTIFIED_CHAIN", "J4_INTENTIONS",
             "J6_UNCERTAIN", "J5_CHAIN_REST"]


def main():
    meta = {r["id"]: r for r in json.load(open(OA))}
    rows = list(csv.DictReader(open(FETCH)))
    fails = [r for r in rows if r["ok"] != "True"]

    buckets = defaultdict(list)
    for r in fails:
        m = meta.get(r["id"], {})
        kind = r["note"].split(":")[0]
        if kind == "route_blocked" or (m.get("is_oa") and kind != "no_candidate_url"):
            buckets["browser"].append((r, m))
        elif not m.get("doi") and not m.get("best_url"):
            buckets["no_route"].append((r, m))
        else:
            buckets["proxy"].append((r, m))

    def key(pair):
        r, m = pair
        j = m.get("job", "J5_CHAIN_REST")
        return (JOB_ORDER.index(j) if j in JOB_ORDER else 99, m.get("title") or "")

    for b in buckets:
        buckets[b].sort(key=key)

    def write_list(path, pairs, header):
        with open(path, "w") as fh:
            fh.write(header)
            for r, m in pairs:
                url = m.get("best_url") or (f"https://doi.org/{m['doi']}" if m.get("doi") else "")
                fh.write(f"\n# [{m.get('job','?')}] {(m.get('title') or '')[:88]}\n")
                fh.write(f"#   {m.get('venue') or '?'} · {m.get('year') or '?'} · "
                         f"{'ANCHOR' if m.get('is_anchor') else m.get('screen_arm','')}\n")
                fh.write(f"{url or '(no url — search by title)'}\n")

    write_list(OUT_BROWSER, buckets["browser"],
               "# BROWSER-JOB — open-access content a script cannot fetch (bot defence).\n"
               "# No institutional access needed. Open each URL in a browser and save the PDF into\n"
               f"# literature/pdfs/{SLUG}/ named  <WID>__<title-slug>.pdf\n"
               "# Ordered by job: J1 is the chapter's registered estimand — do those first.\n")
    write_list(OUT_PROXY, buckets["proxy"] + buckets["no_route"],
               "# PROXY-JOB — genuinely closed papers. Needs UChicago proxy or ILL.\n"
               "# Entries with '(no url)' have neither a DOI nor an open location and need a title\n"
               "# search by a person; they are NOT paywalls and are listed last within each job.\n")

    pc = lambda n, d: f"{n / d:.0%}" if d else "n/a"
    n_ok = sum(1 for r in rows if r["ok"] == "True")
    job_counts = {b: Counter(m.get("job") for _, m in v) for b, v in buckets.items()}

    L = [f"# Stage 5c library wantlist — {SLUG} (C.3.g)", "",
         f"**Generated by:** `source/build/goldset/209_c3g_library_wantlist.py`", "",
         f"{n_ok} of {len(rows)} retrieved automatically ({pc(n_ok, len(rows))}); "
         f"**{len(fails)} need a human**, split by what is actually missing.", "",
         "| Handoff | n | What is missing | Who can do it |", "|---|---|---|---|",
         f"| **browser-job** | {len(buckets['browser'])} | nothing — the content is open and a "
         "script cannot have it | anyone with a browser |",
         f"| **proxy-job** | {len(buckets['proxy'])} | institutional access | someone with the "
         "UChicago proxy |",
         f"| **no-route** | {len(buckets['no_route'])} | a findable copy at all | a person "
         "searching by title |", "",
         "Putting a blocked route in front of someone with a proxy wastes their time: the proxy is "
         "not what is missing. On A.17 that mistake would have covered 67 of 98 failures.", "",
         "## By job — J1 first, because that is the chapter's own estimand", "",
         "| Job | browser | proxy | no-route |", "|---|---|---|---|"]
    for j in JOB_ORDER:
        L.append(f"| `{j}` | {job_counts['browser'].get(j, 0)} | {job_counts['proxy'].get(j, 0)} | "
                 f"{job_counts['no_route'].get(j, 0)} |")
    L += ["", f"Lists: `{os.path.relpath(OUT_BROWSER, ROOT)}` and "
          f"`{os.path.relpath(OUT_PROXY, ROOT)}`.", "",
          "## Findings", "",
          "*Written after reading stage 5b's rung table and this split; both scripts regenerate.*",
          "",
          "- **THE BINDING CONSTRAINT IS NOT THE RETRIEVAL RATE, IT IS WHICH RECORDS ARE MISSING.** "
          "23 of 114 overall and 6 of 19 in J1 are unhappy numbers but survivable ones. This is not: "
          "**all four identified direct-arm records are outstanding.** The chapter's registered "
          "estimand has 19 records, six in hand, and **none of its identified evidence** — the "
          "survey experiment, the FAFSA-IV dissertation chapter, the tuition-IV *Debt burden after "
          "college*, and the SSRN preprint. What was retrieved is the associational and descriptive "
          "tail. A chapter written on what is currently on disk would rate its own claim on its "
          "weakest six records.",
          "- **The chain arm is better off, which sharpens the same problem.** 3 of 9 identified "
          "chain records are in hand and they are the strongest ones in the frame — Mezza et al. in "
          "both versions, and Goodman, Isen and Yannelis. So the retrieval state amplifies the "
          "chapter's structural asymmetry rather than correcting it: the arm that answers the "
          "neighbouring question is the arm with full texts.",
          "- **THE WORKING-PAPER RUNG WAS A WRONG PREDICTION, AND THE REASON IS DIAGNOSABLE.** It "
          "was added because this literature is full of paywalled articles with free NBER/FEDS "
          "twins. It found **1 URL and fetched 0**. The mechanism: those twins are SEPARATE "
          "OpenAlex records with their own DOIs, already in the wantlist in their own right, and "
          "their `best_oa_location` points straight at the free PDF — so rung 0 catches them and "
          "rung 2 never fires. The rung was redundant, not misconceived, and the version-pair "
          "structure that motivated it is real. Retired for the next chapter with the reason "
          "recorded, so it is not re-invented.",
          "- **PMC did not return zero — it returned zero FETCHES on 4 FOUND urls.** The prediction "
          "was that a non-biomedical literature would have no PMC coverage at all. It has a little. "
          "Counting only fetches would have shown `0` and read as absence, which is exactly the "
          "failure the two-counter rule exists to prevent, and it has now fired in three "
          "consecutive chapters. On the evidence across A.12, A.24, A.17 and C.3.g, PMC earns its "
          "place only in clinical literatures; the rung should be conditional on the chapter, not "
          "carried by habit.",
          "- **Rung 0 did essentially all the work: 43 URLs found, and every fetch that succeeded "
          "came from it.** Rungs 1, 2, 3 and 4 found 17 URLs between them and fetched nothing. That "
          "is the third chapter in a row where the cheap sweep of OpenAlex locations is the whole "
          "recovery story.",
          f"- **{len([1 for _, m in buckets['browser'] if m.get('is_oa')])} of the "
          f"{len(buckets['browser'])} browser-job records are flagged OPEN ACCESS by OpenAlex.** "
          "They are free, and a script cannot have them. This is the third chapter to meet it and "
          "the second to meet it before the fetch even ran — the P2 retrieval hit 403s from WUSTL "
          "Open Scholarship and SAGE on open content. The right handoff is a browser and thirty "
          "minutes, not a library proxy.",
          "- **32 records have no route at all** — no DOI and no open location. They are listed "
          "separately rather than folded into the proxy pile, because a person with credentials "
          "cannot help with them: they need a title search first. Half of them are J5 and J6, but "
          "**three are J1**, and those three are direct-arm records currently invisible to every "
          "automated route.", ""]
    open(OUT_MD, "w").write("\n".join(L) + "\n")
    print(f"browser {len(buckets['browser'])} · proxy {len(buckets['proxy'])} · "
          f"no-route {len(buckets['no_route'])}")
    print(f"-> {os.path.relpath(OUT_MD, ROOT)}")


if __name__ == "__main__":
    main()
