#!/usr/bin/env python3
"""TICK-047 stratum C: fetch abstracts for the 122 INSUFFICIENT_INFO records.

Stratum C exists because 27.9% of the D.3.b frame was title-only, and the rubric's
title-only policy correctly refused to invent a substantive cell for a record it knew
nothing about. Those records were parked as UNCERTAIN / INSUFFICIENT_INFO.

Re-reading them on the same title adds nothing -- it reproduces the screen. The only
thing that resolves them is getting the abstract the screen never had. This script does
that mechanical half: OpenAlex `abstract_inverted_index` (reconstructed to plain text)
with a Crossref fallback. Whatever it recovers becomes screenable evidence; whatever it
does not is a genuine full-text-or-drop decision rather than a re-read.

This matters more than it did at the start of the gate. Stratum A cut the realized pool
from 8 to 5, so stratum C is now the only route to ADDITIONAL evidence in the chapter
rather than a tidying exercise.

Outputs:
  extraction/{slug}-stratum-c-abstracts.json
  literature/search-logs/{slug}-stratum-c-recovery.md
"""
from __future__ import annotations

import csv
import json
import subprocess
import time
from pathlib import Path

SLUG = "climate-anxiety-eco-doomerism"
ROOT = Path(__file__).resolve().parents[3]
GATE = ROOT / "extraction" / f"{SLUG}-ra-gate.csv"
OUT = ROOT / "extraction" / f"{SLUG}-stratum-c-abstracts.json"
REPORT = ROOT / "literature" / "search-logs" / f"{SLUG}-stratum-c-recovery.md"
MAILTO = "shravanh@uchicago.edu"
UA = "Mozilla/5.0 (fertility-review-causes; mailto:shravanh@uchicago.edu)"


def unindex(inv: dict | None) -> str:
    """OpenAlex stores abstracts as {token: [positions]}. Rebuild the text."""
    if not inv:
        return ""
    slots: list[tuple[int, str]] = []
    for tok, positions in inv.items():
        for p in positions:
            slots.append((p, tok))
    return " ".join(t for _, t in sorted(slots))


def openalex_batch(work_ids: list[str]) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for i in range(0, len(work_ids), 50):
        chunk = work_ids[i : i + 50]
        url = (
            "https://api.openalex.org/works"
            f"?filter=openalex_id:{'|'.join(chunk)}&per-page=50"
            "&select=id,doi,title,abstract_inverted_index,type,publication_year"
            f"&mailto={MAILTO}"
        )
        try:
            p = subprocess.run(["curl", "-sL", "--max-time", "45", "-A", UA, url],
                               check=True, capture_output=True)
            for w in json.loads(p.stdout).get("results", []):
                out[w["id"].rsplit("/", 1)[-1]] = w
        except (subprocess.CalledProcessError, json.JSONDecodeError):
            pass
        time.sleep(0.35)
    return out


def crossref_abstract(doi: str) -> str:
    if not doi:
        return ""
    d = doi.replace("https://doi.org/", "")
    url = f"https://api.crossref.org/works/{d}?mailto={MAILTO}"
    try:
        p = subprocess.run(["curl", "-sL", "--max-time", "30", "-A", UA, url],
                           check=True, capture_output=True)
        msg = json.loads(p.stdout).get("message", {})
        raw = msg.get("abstract") or ""
        # Crossref abstracts are JATS XML fragments.
        import re
        return re.sub(r"<[^>]+>", " ", raw).strip()
    except (subprocess.CalledProcessError, json.JSONDecodeError):
        return ""


def main() -> None:
    rows = [r for r in csv.DictReader(open(GATE)) if r["stratum"] == "C_INSUFFICIENT_INFO"]
    ids = [r["work_id"] for r in rows if r["work_id"].startswith("W")]
    meta = openalex_batch(ids)

    out, n_oa, n_cr, n_none = [], 0, 0, 0
    for r in rows:
        w = meta.get(r["work_id"], {})
        abstract = unindex(w.get("abstract_inverted_index"))
        source = "openalex" if abstract else ""
        if not abstract:
            abstract = crossref_abstract(r["doi"])
            source = "crossref" if abstract else "none"
            time.sleep(0.2)
        if source == "openalex":
            n_oa += 1
        elif source == "crossref":
            n_cr += 1
        else:
            n_none += 1
        out.append({
            "work_id": r["work_id"], "doi": r["doi"], "year": r["year"],
            "venue": r["venue"], "title": r["title"],
            "type": w.get("type", ""), "abstract_source": source,
            "abstract": abstract[:4000],
        })

    OUT.write_text(json.dumps(out, indent=2, ensure_ascii=False))

    recovered = n_oa + n_cr
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(f"""# Stratum C — abstract recovery for the INSUFFICIENT_INFO records

Generated by `source/build/goldset/86_d3b_stratum_c_abstracts.py`.

The screen parked {len(rows)} records as `UNCERTAIN` / `INSUFFICIENT_INFO` because they
were title-only and the rubric's title-only policy forbids inventing a substantive cell
for a record you know nothing about. Re-reading them on the same title would reproduce
the screen rather than check it, so the gate's real task here is to recover the abstract
the screen never had.

| | n |
|---|---|
| Stratum C records | {len(rows)} |
| Abstract recovered from OpenAlex | {n_oa} |
| Abstract recovered from Crossref | {n_cr} |
| **Total now screenable** | **{recovered}** |
| Still no abstract | {n_none} |

Recovered abstracts are in `extraction/{SLUG}-stratum-c-abstracts.json`.

## What this does and does not settle

It makes {recovered} records screenable that were not before. It does **not** screen
them: that is a substantive pass and it should be run under rubric v2 with the same
blinding as the original screen, then gated.

The {n_none} with no abstract anywhere are a genuine full-text-or-drop decision. They
should not be silently dropped — the screen report's title-only ceiling of 27.9% is
already a stated limit of this chapter, and whatever happens to these records belongs in
that paragraph.

## Why this stratum matters more than it did this morning

Stratum A cut the realized-fertility pool from 8 to 5 and the desire-independence cell
from 4 to 1 or 2. Stratum C is now the only route to *additional* evidence in this
chapter rather than a tidying exercise. Any record here that resolves into
`REALIZED_FERTILITY` or `DESIRE_INDEPENDENCE` is worth more than anything else the gate
can produce.
""")

    print(f"stratum C: {len(rows)} records")
    print(f"  abstract from OpenAlex: {n_oa}")
    print(f"  abstract from Crossref: {n_cr}")
    print(f"  none available:         {n_none}")
    print(f"  -> now screenable:      {recovered}")
    print(f"abstracts -> {OUT.relative_to(ROOT)}")
    print(f"report    -> {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
