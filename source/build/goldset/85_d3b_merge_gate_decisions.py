#!/usr/bin/env python3
"""TICK-047: merge authored gate decisions into the RA gate worksheet.

Keeps the project's no-manual-steps rule intact for a step that is irreducibly human.
The decisions live in an authored input file
(`extraction/{slug}-ra-gate-decisions.csv`); this script merges them into the generated
worksheet and reports the overturn rate. Editing the worksheet by hand would put a
human judgement inside a generated artefact, where the next run of
`84_d3b_ra_gate_worksheet.py` would silently erase it.

`proposer` on each decision row is carried through to `ra_initials` verbatim. Rows
proposed by Claude are marked `claude-proposed` or `claude-escalated` and are NOT a
sign-off: they are a reading of the full text (or an explicit statement that only the
screen record was available) put in front of the RA for adjudication. Replace the value
with your initials as you accept each one.

Outputs (in place):
  extraction/{slug}-ra-gate.csv
  literature/search-logs/{slug}-ra-gate-stratum-a-report.md
"""
from __future__ import annotations

import csv
from pathlib import Path

SLUG = "climate-anxiety-eco-doomerism"
ROOT = Path(__file__).resolve().parents[3]
GATE = ROOT / "extraction" / f"{SLUG}-ra-gate.csv"
DECISIONS = ROOT / "extraction" / f"{SLUG}-ra-gate-decisions.csv"
REPORT = ROOT / "literature" / "search-logs" / f"{SLUG}-ra-gate-stratum-a-report.md"

# An overturn is a decision that moves a record out of the cell or verdict the automated
# screen assigned it. Qualified agreement and pending-full-text are NOT overturns, and
# folding them in would flatter the screen's error rate in one direction and the gate's
# productivity in the other.
OVERTURN_VALUES = {"proposed_overturn", "proposed_overturn_wall1",
                   "proposed_overturn_pending_fulltext"}


def main() -> None:
    gate_rows = list(csv.DictReader(open(GATE)))
    decisions = {d["work_id"]: d for d in csv.DictReader(open(DECISIONS))}

    applied = 0
    for r in gate_rows:
        d = decisions.get(r["work_id"])
        if not d:
            continue
        r["ra_verdict"] = d["proposed_verdict"]
        r["ra_cell"] = d["proposed_cell"]
        r["ra_route_to"] = "D.1.a" if d["agree_or_overturn"] == "proposed_overturn_wall1" else ""
        r["agree_or_overturn"] = d["agree_or_overturn"]
        r["ra_reason"] = d["note"]
        r["send_to_fulltext"] = d["send_to_fulltext"]
        r["ra_initials"] = d["proposer"]
        r["ra_date"] = "2026-07-27"
        applied += 1

    with open(GATE, "w", newline="") as fh:
        wtr = csv.DictWriter(fh, fieldnames=list(gate_rows[0].keys()))
        wtr.writeheader()
        wtr.writerows(gate_rows)

    dec = list(decisions.values())
    verified = [d for d in dec if d["verified_on"] == "full_text"]
    screen_only = [d for d in dec if d["verified_on"] != "full_text"]
    overturns = [d for d in dec if d["agree_or_overturn"] in OVERTURN_VALUES]
    escalated = [d for d in dec if d["agree_or_overturn"] == "escalated_to_ra"]
    retrieval = [d for d in dec if d["send_to_fulltext"] == "yes"]

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    with open(REPORT, "w") as fh:
        fh.write(f"""# RA gate — stratum A (the decisive 12) — {SLUG}

Generated by `source/build/goldset/85_d3b_merge_gate_decisions.py` from the authored
decisions in `extraction/{SLUG}-ra-gate-decisions.csv`.

**These are proposed verdicts, not a completed sign-off.** {len(verified)} of {len(dec)}
were checked against full text; the other {len(screen_only)} could only be read on the
screen record, because TICK-048 retrieval reached its automated ceiling. A gate decision
made on the screen record alone is not an independent check — it re-reads the same
title and abstract the automated screener saw. Those rows are marked
`pending_fulltext` and should not be treated as gated.

## Counts

| | n |
|---|---|
| Stratum A records | {len(dec)} |
| Verified on full text | {len(verified)} |
| Screen record only (NOT independently gated) | {len(screen_only)} |
| Proposed overturns | {len(overturns)} |
| Escalated to the RA | {len(escalated)} |
| Flagged for retrieval priority | {len(retrieval)} |

Overturn rate **on the rows that could actually be checked**: {len(overturns)} of
{len(dec)} stratum-A records, but only {sum(1 for d in overturns if d['verified_on'] == 'full_text')}
of the {len(verified)} verified on full text. Quoting the first number alone would
overstate what the gate has established.

## What the gate found

**A Wall 1 failure in the realized-fertility pool (`W4414495777`).** Traylor and Chae's
independent variable is support for government spending on the environment, and the
paper frames itself in Inglehart's postmaterialist values theory by name. That is
environmentalism-as-value, not ecological fear, and under Wall 1 clause (a) it routes to
D.1.a. The paper's only D.3.b-shaped estimate — perceived danger from a rise in world
temperature — is null and sits in Online Supplement A3 on 32% of the sample. Carrying
the headline coefficient into a D.3.b pool would report a postmaterialist value effect
as evidence of ecological dread, which is the precise failure chapter section 9 warns
about. Recommended resolution is to keep the study but extract only the supplementary
null.

**A category error in the realized pool (`W2590537621`).** The Scottish Journal of
Political Economy 2017 entry is a formal growth model with no empirical realized
fertility. The structurally identical Gerlagh, Lupi and Galeotti paper is already in
this review's theory stream as `ECO_ETHICS_THEORY` / structural, so consistency decides
this one rather than judgement.

**A likely over-promotion in the distinctive cell (`W4402549764`).** The DI cell
requires the design to separate fear from desire and says a respondent subgroup saying
so belongs in a PRIMARY cell instead. A single item asking respondents to attribute a
shortfall to climate emotions is that subgroup report. Proposed overturn, but it needs
full text to confirm — and it is one of only four studies in the cell the hypothesis is
named for.

**A factual error in the skeleton chapter (`W4411020223`).** The PLoS ONE
desire-independence study is set in **Bangladesh**, at Shahjalal University of Science
and Technology. Chapter section 8 states the evidence base concentrates in Europe and
North America, and section 12 lists a study in a high-fertility setting as a missing
extension. Both claims are wrong as written and must be corrected at TICK-053.

**A well-powered null that must not be lost (`W4412670275`).** Jylhä, Kolk and
Fairbrother, Swedish GGS N=8027, conclude there is no clear evidence that environmental
concerns affect childbearing decisions in Sweden. It is the largest sample in the
realized stratum. TICK-051 must not pool the small positive studies without it.

## One call escalated rather than decided

`W4410884918`, the AEA P&P air-pollution study. Precision rule 3 excludes physical
exposure *with no affective or attitudinal mechanism*, and this design explicitly routes
through information access and climate anxiety, so the rule does not straightforwardly
bite — but the identifying variation is still physical exposure. The rubric genuinely
cuts both ways. My weak lean is exclude; it is a scope judgement and it is yours.

## Effect on the counts if the proposals are accepted

Realized-fertility pool 8 → **7** (the growth model leaves). If the AEA study is also
excluded, the empirical realized base is **6**, and `W4414495777` contributes only a
null — so the realized evidence for a positive effect would rest on at most **5**
studies, of which one is a preprint and one a working paper.

Desire-independence 4 → **3** if the `W4402549764` overturn holds on full text.

Every one of these numbers appears in chapter sections 1, 5.2, 5.3, 10 and 12, and in
`output/{SLUG}-screen-report.md`. TICK-053 must update both, not just the chapter.

## Retrieval priorities coming out of the gate

{len(retrieval)} records flagged `send_to_fulltext=yes`. In order:

1. `10.1111/padr.12646` — Golovina and Jokela, SOEP. The best-identified positive
   finding in the stratum and the one most likely to carry a pooled estimate.
   `oa_but_blocked`; a browser should get it.
2. `10.1111/jomf.70095` — the UKHLS life-course panel measuring both outcome levels.
   `oa_but_blocked`.
3. `10.1016/j.joclim.2024.100346` — needed to confirm or reject the DI overturn.
   `oa_but_blocked` behind PMC's interstitial.
4. `10.1080/23251042.2024.2408779` — the strongest remaining DI candidate. Genuinely
   `closed`; needs the UChicago proxy.
5. `10.1215/22011919-11713414` — qualitative, non-poolable whatever the cell.
""")

    print(f"applied {applied} decisions -> {GATE.relative_to(ROOT)}")
    print(f"  full-text verified: {len(verified)}   screen-record only: {len(screen_only)}")
    print(f"  proposed overturns: {len(overturns)}  escalated: {len(escalated)}")
    print(f"report -> {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
