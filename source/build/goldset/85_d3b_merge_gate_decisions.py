#!/usr/bin/env python3
"""TICK-047: merge authored gate decisions into the RA gate worksheet.

Keeps the project's no-manual-steps rule intact for a step that is irreducibly human.
The decisions live in an authored input file
(`extraction/{slug}-ra-gate-decisions.csv`); this script merges them into the generated
worksheet and reports the overturn rate. Editing the worksheet by hand would put a
human judgement inside a generated artefact, where the next run of
`84_d3b_ra_gate_worksheet.py` would silently erase it.

`proposer` on each decision row is carried through to `ra_initials` verbatim. Rows
proposed by Claude are marked `claude-proposed` or `claude-escalated` and are NOT a
sign-off: they are a reading of the full text (or an explicit statement that only the
screen record was available) put in front of the RA for adjudication. Replace the value
with your initials as you accept each one.

Outputs (in place):
  extraction/{slug}-ra-gate.csv
  literature/search-logs/{slug}-ra-gate-stratum-a-report.md
"""
from __future__ import annotations

import csv
from pathlib import Path

SLUG = "climate-anxiety-eco-doomerism"
ROOT = Path(__file__).resolve().parents[3]
GATE = ROOT / "extraction" / f"{SLUG}-ra-gate.csv"
DECISIONS = ROOT / "extraction" / f"{SLUG}-ra-gate-decisions.csv"
REPORT = ROOT / "literature" / "search-logs" / f"{SLUG}-ra-gate-stratum-a-report.md"

# An overturn is a decision that moves a record out of the cell or verdict the automated
# screen assigned it. Qualified agreement and pending-full-text are NOT overturns, and
# folding them in would flatter the screen's error rate in one direction and the gate's
# productivity in the other.
OVERTURN_VALUES = {"proposed_overturn", "proposed_overturn_wall1",
                   "proposed_overturn_pending_fulltext",
                   "overturn_wall1_ra_decided"}
WALL1_VALUES = {"proposed_overturn_wall1", "overturn_wall1_ra_decided"}
RA_DECIDED = {"agree_ra_decided", "overturn_wall1_ra_decided"}


def main() -> None:
    gate_rows = list(csv.DictReader(open(GATE)))
    decisions = {d["work_id"]: d for d in csv.DictReader(open(DECISIONS))}

    applied = 0
    for r in gate_rows:
        d = decisions.get(r["work_id"])
        if not d:
            continue
        r["ra_verdict"] = d["proposed_verdict"]
        r["ra_cell"] = d["proposed_cell"]
        r["ra_route_to"] = "D.1.a" if d["agree_or_overturn"] in WALL1_VALUES else ""
        r["agree_or_overturn"] = d["agree_or_overturn"]
        r["ra_reason"] = d["note"]
        r["send_to_fulltext"] = d["send_to_fulltext"]
        r["ra_initials"] = d["proposer"]
        r["ra_date"] = "2026-07-27"
        applied += 1

    with open(GATE, "w", newline="") as fh:
        wtr = csv.DictWriter(fh, fieldnames=list(gate_rows[0].keys()))
        wtr.writeheader()
        wtr.writerows(gate_rows)

    dec = list(decisions.values())
    verified = [d for d in dec if d["verified_on"] == "full_text"]
    screen_only = [d for d in dec if d["verified_on"] != "full_text"]
    overturns = [d for d in dec if d["agree_or_overturn"] in OVERTURN_VALUES]
    escalated = [d for d in dec if d["agree_or_overturn"] == "escalated_to_ra"]
    retrieval = [d for d in dec if d["send_to_fulltext"] == "yes"]

    wall1 = [d for d in dec if d["agree_or_overturn"] in WALL1_VALUES]
    ra_decided = [d for d in dec if d["agree_or_overturn"] in RA_DECIDED]

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    with open(REPORT, "w") as fh:
        fh.write(f"""# RA gate — stratum A (the decisive 12) — {SLUG}

Generated by `source/build/goldset/85_d3b_merge_gate_decisions.py` from the authored
decisions in `extraction/{SLUG}-ra-gate-decisions.csv`.

**Mixed provenance — read the `proposer` column.** {len(ra_decided)} decisions were made
by the RA (Shravan, 2026-07-27) and are binding. The rest are `claude-proposed`: a
reading of the full text, or an explicit statement that only the screen record was
available, put up for adjudication. {len(verified)} of {len(dec)} were checked against
full text; the other {len(screen_only)} could not be, and a gate decision on the screen
record alone is not an independent check — it re-reads the same title and abstract the
automated screener saw.

## Counts

| | n |
|---|---|
| Stratum A records | {len(dec)} |
| Verified on full text | {len(verified)} |
| Screen record only (NOT independently gated) | {len(screen_only)} |
| Overturns (proposed or RA-decided) | {len(overturns)} |
| of which Wall 1 (routed to D.1.a) | {len(wall1)} |
| Decided by the RA | {len(ra_decided)} |
| Still flagged for retrieval | {len(retrieval)} |

**{len(overturns)} of the {len(verified)} records we could read on full text were
overturned.** That is the headline number and it should be read as a measure of the
automated screen, not of the studies.

## The systematic finding: the screen cannot see the D.1.a boundary

Three of the eight realized-fertility studies turned out to measure **environmentalism
as a value or a behaviour** rather than ecological fear:

| Study | What the exposure actually is |
|---|---|
| Traylor & Chae (`W4414495777`) | Support for government spending on the environment; the paper names Inglehart postmaterialist values theory in its own keywords |
| Ivanova & Rüttenauer (`W7165518406`) | An index of seven pro-environmental household habits — TV standby, switching off lights, tap running while brushing teeth, own shopping bag |
| Sasser & Merchant (`W4402549764`) | (Different failure: a respondent-attributed wanted-minus-planned gap, which the DI cell sends to a PRIMARY cell) |

**This is not screener sloppiness and it is not fixable by rewriting the rubric.** Wall 1
turns on what the exposure variable *contains*, and that lives in the measures section.
It is invisible in a title and abstract, which is all the screen ever sees. Both papers
describe themselves in the abstract as studying "environmental concern" or
"environmentalism" and fertility — correctly, and in language indistinguishable from a
genuine D.3.b study.

**The consequence for the rest of the chapter is larger than these three rows.** The
gate's stratum B samples the 50 records routed *out* to D.1.a, which tests false
exclusions. The error we actually found runs the other way: D.1.a studies retained *in*
the D.3.b pool. Nothing in the current gate design tests that direction, and the 61
remaining stated-intention studies have never been checked for it. On a base rate of
2 Wall 1 failures in 8 realized studies, the stated pool should be assumed to contain
them until shown otherwise. **Recommend adding a stratum E: a measure-level Wall 1
check on the stated pool, which can only be done from full text and should therefore be
folded into TICK-049 extraction as a required field rather than run as a separate pass.**

## What is left of the realized-fertility evidence

Starting from 8: the growth model leaves as a category error, Traylor & Chae and
Ivanova & Rüttenauer leave under Wall 1. That leaves **five**:

| Study | Status |
|---|---|
| Golovina & Jokela (PDR, GSOEP) | The load-bearing study. Climate-specific worry, 16% lower likelihood of parenthood, adjusted for political attitudes |
| Jylhä, Kolk & Fairbrother (Sweden, N=8027) | Well-powered NULL |
| Peters et al. (MPIDR) | Working paper; the reverse-causality design. **Shares GSOEP with Golovina & Jokela — not an independent sample** |
| Weychert et al. (Research Square) | Preprint; treatment is climate news exposure |
| Air pollution (AEA P&P) | Retained by RA decision; identifies off physical exposure |

**After the gate, the peer-reviewed realized-fertility evidence for a positive effect of
ecological dread on births rests on essentially one estimate** — Golovina & Jokela's
16% — with a well-powered null beside it and the two GSOEP studies not independent of
each other. That is a materially thinner base than the skeleton chapter describes, and
it is the single most important input to the eventual GRADE rating.

## Two errors found in the chapter itself

**A wrong title (`W4412706512`).** OpenAlex records the work as "A Crude, Cruel Crisis";
the DOI, volume, issue and pages all match but the actual article is McMullen, Dow and
Lakind, "The Fossil Family and Reproductive Impasse during Climate Change". Chapter
section 5.3 cites the wrong title. Same family as the OAS ghost-citation finding: a
metadata field trusted without opening the paper. The paper is also interpretive
humanities scholarship, so it is proposed out of DESIRE_INDEPENDENCE into the theory
stream — it was never poolable under any cell.

**A wrong claim about scope (`W4411020223`).** The PLoS ONE desire-independence study is
set in **Bangladesh**. Chapter section 8 says the evidence concentrates in Europe and
North America, and section 12 lists a study in a high-fertility setting as a missing
extension. Both are wrong as written.

## The distinctive cell is now nearly empty

Of the four DESIRE_INDEPENDENCE studies, two are proposed out (Sasser & Merchant to a
PRIMARY cell, McMullen et al. to theory) and one survives only in the weak form
(`W4411020223`, Bangladesh, and its only significant environmental predictor is a
carbon-ethics item). **`W4403512936` — Environmental Sociology, still unretrieved and
genuinely closed — is now the only candidate for a real desire-independence design in
the entire review.** If it does not hold on full text, the cell the hypothesis is named
for is empty. It is the most important outstanding retrieval in the chapter and it needs
the UChicago proxy.

## Effect on the counts

Realized pool 8 → **5**. Stated pool 62 → **61** (Traylor & Chae was `BOTH`).
Desire-independence 4 → **1 or 2**. Theory stream gains 2.

Every one of these appears in chapter sections 1, 5.2, 5.3, 10 and 12 and in
`output/{SLUG}-screen-report.md`. TICK-053 must update both.
""")

    print(f"applied {applied} decisions -> {GATE.relative_to(ROOT)}")
    print(f"  full-text verified: {len(verified)}   screen-record only: {len(screen_only)}")
    print(f"  proposed overturns: {len(overturns)}  escalated: {len(escalated)}")
    print(f"report -> {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
