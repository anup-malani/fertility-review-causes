#!/usr/bin/env python3
"""
389 — C.3.f: primary yield per retrieval channel, from the verdicts.

The question every earlier script has been circling: which channel actually finds the registered
estimand? Recall against anchors answered a different question — whether a channel reaches works we
already knew about. This answers whether it reaches records we did not.

`generate-result-tables-never-retype`. Every figure in the write-up comes from here.

A record reached by several channels is credited to each, so the columns do not sum to the total.
The `unique` column is the one that decides whether a channel is carrying its weight: primary
records that NO other channel reached.

Output literature/search-logs/c3f-channel-yield-<date>.md.
"""
import csv, json, collections, datetime, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
LOGS = ROOT / "literature" / "search-logs"
DATE = datetime.date.today().isoformat()
PRIMARY = {"NET_FLOW_FERTILITY", "SHOCK_NET_FERTILITY"}


def main():
    verdicts = list(csv.DictReader((ROOT / "extraction" /
                                    "wealth-flows-reversal-screen-verdicts.csv").open()))
    univ = {r["screen_id"]: r for r in
            json.loads((ROOT / "temp" / "c3f-universe-hydrated.json").read_text())["records"]
            if r.get("screen_id")}

    size = collections.Counter()
    for r in univ.values():
        for p in r.get("provenance") or []:
            size[p] += 1
    screened = collections.Counter()
    for v in verdicts:
        for p in univ.get(v["screen_id"], {}).get("provenance") or []:
            screened[p] += 1

    prim = [v for v in verdicts if v["cell"] in PRIMARY]
    found, unique = collections.Counter(), collections.Counter()
    for v in prim:
        prov = univ[v["screen_id"]].get("provenance") or []
        for p in prov:
            found[p] += 1
        if len(prov) == 1:
            unique[prov[0]] += 1

    rows = []
    for ch in sorted(size, key=lambda c: -found[c]):
        cov = 100 * screened[ch] / size[ch] if size[ch] else 0.0
        rows.append((ch, size[ch], screened[ch], cov, found[ch], unique[ch],
                     100 * found[ch] / screened[ch] if screened[ch] else 0.0))

    print(f"{'channel':44} {'size':>6} {'scr':>5} {'cov':>6} {'prim':>5} {'uniq':>5} {'yield':>7}")
    for ch, n, s, c, f, u, y in rows:
        flag = "  <- too little screened to compare" if c < 20 else ""
        print(f"{ch[:44]:44} {n:>6} {s:>5} {c:>5.0f}% {f:>5} {u:>5} {y:>6.1f}%{flag}")

    md = [f"# C.3.f — primary yield per retrieval channel — {DATE}", "",
          "Generated by `source/build/goldset/389_c3f_channel_yield.py` from the verdicts. Do not",
          "edit by hand.", "",
          "`size` is the channel's records in the universe, `screened` how many of them carry a",
          "verdict yet, `primary` how many of those are `NET_FLOW_FERTILITY` or",
          "`SHOCK_NET_FERTILITY`, and **`unique` is primary records no other channel reached**.",
          "A record reached by several channels is credited to each, so the columns do not sum.", "",
          "**The yields are NOT yet comparable across rows.** Coverage is deliberately uneven —",
          "the probe sampled the whole universe and the channel batches screen one arm",
          "exhaustively — so a channel with low coverage has a yield estimated on very few records.",
          "A row under 20% coverage is marked; read its yield as a signal to screen it next, never",
          "as a measurement of the channel.", "",
          "| channel | size | screened | coverage | primary | unique | yield | |",
          "|---|---|---|---|---|---|---|---|"]
    md += [f"| `{ch}` | {n:,} | {s:,} | {c:.0f}% | {f} | {u} | {y:.1f}% | "
           f"{'**thin**' if c < 20 else ''} |" for ch, n, s, c, f, u, y in rows]
    md += ["", f"Totals: **{len(prim)} primary records** from **{len(verdicts)} verdicts**.", "",
           "The only row that is a finished measurement is the one at 100% coverage.", ""]
    (LOGS / f"c3f-channel-yield-{DATE}.md").write_text("\n".join(md))
    print(f"\n{len(prim)} primary from {len(verdicts)} verdicts")
    print(f"wrote c3f-channel-yield-{DATE}.md")


main()
